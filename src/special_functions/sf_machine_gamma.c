/* Stirling: lnGamma(w) = (w - 1/2) log w - w + log sqrt(2 pi)
 *                        + sum_{k=1}^{12} B_2k / (2k (2k-1) w^(2k-1)),
 * for Re w >= 7 (or |w| >= 25, Re w >= 0). The first omitted term is below
 * 6e-18 at |w| = 7 (DLMF 5.11.1, error bound 5.11.ii). */
static void stirling_c(double wr, double wi, double* outr, double* outi) {
    double ir, ii; cx_recip(wr, wi, &ir, &ii);
    double zr, zi; cx_mul(ir, ii, ir, ii, &zr, &zi);
    double pr, pi; poly4_rc(SFG_STIRLING, 12, zr, zi, &pr, &pi);
    cx_mul(pr, pi, ir, ii, &pr, &pi);
    double lr, li; cx_log(wr, wi, &lr, &li);
    double ar, ai; cx_mul(wr - 0.5, wi, lr, li, &ar, &ai);
    *outr = ar - wr + SFG_LN_SQRT_2PI + pr;
    *outi = ai - wi + pi;
}

/* ---- Stirling's series with a double-double exponent (for Gamma) ---------- */

/* Dekker's exact product a*b = p + e (Dekker 1971), by Veltkamp splitting, so
 * no fused multiply-add is needed (the default x86-64 target has none). */
static inline void two_prod(double a, double b, double* p, double* e) {
    const double SPLIT = 134217729.0;           /* 2^27 + 1 */
    double t = SPLIT * a, ah = t - (t - a), al = a - ah;
    t = SPLIT * b;
    double bh = t - (t - b), bl = b - bh;
    *p = a * b;
    *e = ((ah * bh - *p) + ah * bl + al * bh) + al * bl;
}

/* log 2 as fdlibm's split: e * SFG_LN2_HI is exact for |e| < 2^11. */
#define SFG_LN2_HI 6.93147180369123816490e-01
#define SFG_LN2_LO 1.90821492927058770002e-10
#define SFG_LN_SQRT_2PI_LO (-3.87829415806724145e-17)

/* log|w| as hi + lo, to about 2^-58 relative: |w|^2 = S + Se exactly (Dekker),
 * S = 2^e f with f in [sqrt(1/2), sqrt 2), and log f = log1p(f - 1) -- an exact
 * argument, so the one rounding is relative to |log f| <= 0.35, not to log|w|. */
static void logabs_dd(double wr, double wi, double* hi, double* lo) {
    double s, se, t, te;
    two_prod(wr, wr, &s, &se);
    two_prod(wi, wi, &t, &te);
    double S = s + t;
    double Se = two_sum_err(s, t, S) + se + te;
    int e;
    double f = frexp(S, &e);
    if (f < 0.70710678118654752) { f *= 2.0; e--; }
    double lf = log1p(f - 1.0) + Se / S;
    double a = (double)e * SFG_LN2_HI;
    double b = (double)e * SFG_LN2_LO + lf;
    double h = a + b;
    *hi = 0.5 * h;
    *lo = 0.5 * two_sum_err(a, b, h);
}

/* Stirling's lnGamma(w) (as stirling_c) with the exponent's real and imaginary
 * parts carried as double-doubles. exp() turns an ABSOLUTE error of the exponent
 * into a relative error of Gamma, and the plain sum's absolute error is
 * ~|w log w| ulp -- 30 ulp of Gamma at |w| ~ 10. Here the large products are
 * exact (Dekker) and log|w| is extra-precise; what remains is the rounding of
 * arg w (relative to arg w) and of the small series. */
static void stirling_dd(double wr, double wi, double* er, double* ei, double* lr, double* li) {
    double ir, ii; cx_recip(wr, wi, &ir, &ii);
    double zr, zi; cx_mul(ir, ii, ir, ii, &zr, &zi);
    double pr, pi; poly4_rc(SFG_STIRLING, 12, zr, zi, &pr, &pi);
    cx_mul(pr, pi, ir, ii, &pr, &pi);
    double Lh, Ll; logabs_dd(wr, wi, &Lh, &Ll);
    double th = atan2(wi, wr);
    double a = wr - 0.5;                        /* exact for wr >= 1 */
    /* Re = a L - wi th - wr + ln sqrt(2 pi) + Re(series) */
    double p1, e1, p2, e2;
    two_prod(a, Lh, &p1, &e1);
    two_prod(wi, th, &p2, &e2);
    double lo = e1 - e2 + a * Ll + SFG_LN_SQRT_2PI_LO;
    double s = p1 - p2;      lo += two_sum_err(p1, -p2, s);
    double s2 = s - wr;      lo += two_sum_err(s, -wr, s2);
    double s3 = s2 + SFG_LN_SQRT_2PI; lo += two_sum_err(s2, SFG_LN_SQRT_2PI, s3);
    double s4 = s3 + pr;     lo += two_sum_err(s3, pr, s4);
    *er = s4; *lr = lo;
    /* Im = wi L + a th - wi + Im(series) */
    two_prod(wi, Lh, &p1, &e1);
    two_prod(a, th, &p2, &e2);
    lo = e1 + e2 + wi * Ll;
    s = p1 + p2;             lo += two_sum_err(p1, p2, s);
    s2 = s - wi;             lo += two_sum_err(s, -wi, s2);
    s3 = s2 + pi;            lo += two_sum_err(s2, pi, s3);
    *ei = s3; *li = lo;
}

/* Shift count N so that w = z + N is in Stirling's region. False when z is too
 * far into the left half-plane for the recurrence to be economical/safe. */
static bool stirling_shift(double zr, double zi, int* N) {
    if (zr >= 7.0) { *N = 0; return true; }
    if (fabs(zi) >= 25.0) {
        if (zr >= 0.0) { *N = 0; return true; }
        if (zr < -30.0 || fabs(zi) > 1e9) return false;
        *N = (int)ceil(-zr);
        return true;
    }
    if (zr < -30.0) return false;
    *N = (int)ceil(7.0 - zr);
    return true;
}

/* lnGamma(z) for Im z > 0. */
static bool loggamma_upper(double zr, double zi, double* rr, double* ri) {
    double fr, fi, lor, loi; int m;
    if (tile_eval(0, zr, zi, &fr, &fi, &lor, &loi, &m)) {
        fr += lor; fi += loi;
        if (m > 0) {
            /* lnGamma(z) = lnGamma(z - m) + sum_{j=1}^{m} Log(z - j) */
            double pr, pi; int k;
            shift_product(zr - (double)m, zi, m, &pr, &pi, &k);
            double lr, li; cx_log(pr, pi, &lr, &li);
            fr += lr; fi += li + 2.0 * M_PI * (double)k;
        } else if (m == -1) {
            /* lnGamma(z) = lnGamma(z + 1) - Log z, Log z = log1p(z - 1) (z may be
             * near 1, where lnGamma is small) */
            double lr, li; cx_log1p(zr - 1.0, zi, &lr, &li);
            fr -= lr; fi -= li;
        } else if (m < -1) {
            /* lnGamma(z) = lnGamma(z - m) - sum_{j=0}^{-m-1} Log(z + j) */
            double pr, pi; int k;
            shift_product(zr, zi, -m, &pr, &pi, &k);
            double lr, li; cx_log(pr, pi, &lr, &li);
            fr -= lr; fi -= li + 2.0 * M_PI * (double)k;
        }
        *rr = fr; *ri = fi;
        return isfinite(fr) && isfinite(fi);
    }
    int N;
    if (!stirling_shift(zr, zi, &N)) return false;
    double sr, si; stirling_c(zr + (double)N, zi, &sr, &si);
    if (N > 0) {
        double pr, pi; int k;
        shift_product(zr, zi, N, &pr, &pi, &k);
        double lr, li; cx_log(pr, pi, &lr, &li);
        sr -= lr;
        si -= li + 2.0 * M_PI * (double)k;
    }
    *rr = sr; *ri = si;
    return isfinite(sr) && isfinite(si);
}

bool sfg_loggamma_c(double zr, double zi, double* rr, double* ri) {
    if (!isfinite(zr) || !isfinite(zi)) return false;
    if (zi == 0.0) {
        if (!(zr > 0.0)) return false;           /* real axis x <= 0: caller's path */
        double v = lgamma(zr);
        *rr = v; *ri = 0.0;
        return isfinite(v);
    }
    /* LogGamma(conj z) = conj LogGamma(z) off the cut. */
    if (zi > 0.0) return loggamma_upper(zr, zi, rr, ri);
    if (!loggamma_upper(zr, -zi, rr, ri)) return false;
    *ri = -*ri;
    return true;
}

/* Gamma(z) in factored form: Gamma(z) = exp(E + lo) * P^(+-1), where E (with
 * its double-double low part lo) is lnGamma of the reduced argument and P the
 * product of the recurrence factors. Kept factored so that Beta and Pochhammer
 * can combine several Gammas under ONE exponential. */
typedef struct {
    double er, ei;      /* E */
    double lr, li;      /* low part of E (0 off the tiles) */
    double pr, pi;      /* P */
    bool divide;        /* Gamma = exp(E) / P, else exp(E) * P */
} GammaParts;

/* z with Im z >= 0; z is not a pole. */
static bool gamma_parts_upper(double zr, double zi, GammaParts* g) {
    int m;
    g->lr = g->li = 0.0;
    g->pr = 1.0; g->pi = 0.0;
    g->divide = false;
    if (tile_eval(0, zr, zi, &g->er, &g->ei, &g->lr, &g->li, &m)) {
        /* Gamma(z) = exp(lnGamma(z - m)) * (z-1)...(z-m) for m > 0 */
        if (m > 0) {
            int k; shift_product(zr - (double)m, zi, m, &g->pr, &g->pi, &k);
        } else if (m < 0) {
            /* Gamma(z) = Gamma(z - m) / (z (z+1) ... (z-m-1)) */
            if (m == -1) { g->pr = zr; g->pi = zi; }
            else { int k; shift_product(zr, zi, -m, &g->pr, &g->pi, &k); }
            g->divide = true;
        }
        return true;
    }
    int N;
    if (!stirling_shift(zr, zi, &N)) return false;
    double wr = zr + (double)N;
    stirling_dd(wr, zi, &g->er, &g->ei, &g->lr, &g->li);
    if (N > 0) {
        /* wr carries the rounding of zr + N: lnGamma(w + e) = lnGamma(w) + psi(w) e,
         * psi(w) ~ log w here (Re w >= 7), to first order. */
        double ew = two_sum_err(zr, (double)N, wr);
        if (ew != 0.0) {
            double lr2, li2; cx_log(wr, zi, &lr2, &li2);
            g->lr += lr2 * ew; g->li += li2 * ew;
        }
        int k; shift_product(zr, zi, N, &g->pr, &g->pi, &k); g->divide = true;
    }
    return true;
}

static bool gamma_parts(double zr, double zi, GammaParts* g) {
    if (!isfinite(zr) || !isfinite(zi)) return false;
    if (zi == 0.0 && zr <= 0.0 && zr == floor(zr)) return false;       /* pole */
    if (zi >= 0.0) return gamma_parts_upper(zr, zi, g);
    /* Gamma(conj z) = conj Gamma(z) */
    if (!gamma_parts_upper(zr, -zi, g)) return false;
    g->ei = -g->ei; g->li = -g->li; g->pi = -g->pi;
    return true;
}

/* exp(E + lo) * num / den, false on overflow / underflow / non-finite. */
static bool gamma_finish(double er, double ei, double lr, double li,
                         double nr, double ni, double dr, double di,
                         double* rr, double* ri) {
    if (er > 709.0) return false;
    double vr, vi; cx_exp(er, ei, &vr, &vi);
    /* exp(E + lo) = exp(E) (1 + lo) to first order, |lo| <= 2^-52 |E| */
    if (lr != 0.0 || li != 0.0) cx_mul(vr, vi, 1.0 + lr, li, &vr, &vi);
    if (ni != 0.0 || nr != 1.0) cx_mul(vr, vi, nr, ni, &vr, &vi);
    if (di != 0.0 || dr != 1.0) {
        double ir, ii; cx_recip(dr, di, &ir, &ii);
        cx_mul(vr, vi, ir, ii, &vr, &vi);
    }
    if (!isfinite(vr) || !isfinite(vi) || (vr == 0.0 && vi == 0.0)) return false;
    *rr = vr; *ri = vi;
    return true;
}

bool sfg_gamma_c(double zr, double zi, double* rr, double* ri) {
    if (!isfinite(zr) || !isfinite(zi)) return false;
    if (zi == 0.0) {
        if (zr <= 0.0 && zr == floor(zr)) return false;     /* pole */
        double v = tgamma(zr);
        *rr = v; *ri = 0.0;
        return isfinite(v);
    }
    GammaParts g;
    if (!gamma_parts(zr, zi, &g)) return false;
    if (g.divide) return gamma_finish(g.er, g.ei, g.lr, g.li, 1.0, 0.0, g.pr, g.pi, rr, ri);
    return gamma_finish(g.er, g.ei, g.lr, g.li, g.pr, g.pi, 1.0, 0.0, rr, ri);
}

/* prod_i Gamma(z_i)^(sign_i), sign_i = +-1, under ONE exponential: the E's are
 * summed with their rounding errors carried, the products split into a
 * numerator and a denominator for a single division. A product of separately
 * rounded Gamma values would collect each one's exp/cos/sin rounding. */
static bool gamma_combo_c(int n, const double* zr, const double* zi, const int* sign,
                          double* rr, double* ri) {
    double er = 0.0, ei = 0.0, lr = 0.0, li = 0.0;
    double nr = 1.0, ni = 0.0, dr = 1.0, di = 0.0;
    for (int k = 0; k < n; k++) {
        GammaParts g;
        if (!gamma_parts(zr[k], zi[k], &g)) return false;
        double s = (double)sign[k];
        double tr = er + s * g.er, ti = ei + s * g.ei;
        lr += two_sum_err(er, s * g.er, tr) + s * g.lr;
        li += two_sum_err(ei, s * g.ei, ti) + s * g.li;
        er = tr; ei = ti;
        if (g.divide == (sign[k] > 0)) cx_mul(dr, di, g.pr, g.pi, &dr, &di);
        else                           cx_mul(nr, ni, g.pr, g.pi, &nr, &ni);
    }
    return gamma_finish(er, ei, lr, li, nr, ni, dr, di, rr, ri);
}

/* ------------------------------------------------------------------ */
/* Beta                                                               */
/* ------------------------------------------------------------------ */

static inline bool nonpos_int(double x) { return x <= 0.0 && x == floor(x); }

bool sfg_beta(double a, double b, double* out) {
    if (!isfinite(a) || !isfinite(b)) return false;
    if (nonpos_int(a) || nonpos_int(b)) return false;      /* pole lattice: exact path */
    double s = a + b;
    if (nonpos_int(s)) return false;                        /* 1/Gamma(a+b) = 0 */
    if (fabs(a) > 170.0 || fabs(b) > 170.0 || fabs(s) > 170.0) return false;
    double v = (tgamma(a) / tgamma(s)) * tgamma(b);
    /* Gamma(s + e) = Gamma(s) (1 + psi(s) e + O(e^2)): undo the rounding of a+b,
     * which psi(s) amplifies (to ~10 ulp at s ~ 10) if left alone. */
    double e = two_sum_err(a, b, s);
    if (e != 0.0) {
        double ps;
        if (sfg_digamma(s, &ps)) v *= 1.0 - ps * e;
    }
    *out = v;
    return isfinite(v) && v != 0.0;
}

/* Both parts below 100 in magnitude: the factored Gammas combine under one
 * exponential (gamma_combo_c), whose exponent is carried as a double-double on
 * the tiles. Further out exp() of a sum of LogGamma values is used, whose
 * absolute error grows with |lnGamma| -- but so does the condition number. */
static inline bool cx_moderate(double r, double i) {
    return fabs(r) < 100.0 && fabs(i) < 100.0;
}

/* Gamma(p) / Gamma(s) [times Gamma(q) when q is given] for complex arguments:
 * the combined factored form when moderate, else exp of the lnGamma combination.
 * The caller corrects the rounding of s afterwards. */
static bool gamma_ratio_c(double pr, double pi, const double* q, double sr, double si,
                          double* rr, double* ri) {
    if (cx_moderate(pr, pi) && cx_moderate(sr, si) && (!q || cx_moderate(q[0], q[1]))) {
        double zr[3] = { pr, sr, q ? q[0] : 0.0 }, zi[3] = { pi, si, q ? q[1] : 0.0 };
        static const int sg[3] = { 1, -1, 1 };
        if (gamma_combo_c(q ? 3 : 2, zr, zi, sg, rr, ri)) return true;
    }
    double lpr, lpi, lsr, lsi;
    if (!sfg_loggamma_c(pr, pi, &lpr, &lpi)) return false;
    if (!sfg_loggamma_c(sr, si, &lsr, &lsi)) return false;
    double er = lpr - lsr, ei = lpi - lsi;
    if (q) {
        double lqr, lqi;
        if (!sfg_loggamma_c(q[0], q[1], &lqr, &lqi)) return false;
        er += lqr; ei += lqi;
    }
    if (er > 709.0) return false;
    double vr, vi; cx_exp(er, ei, &vr, &vi);
    if (!isfinite(vr) || !isfinite(vi) || (vr == 0.0 && vi == 0.0)) return false;
    *rr = vr; *ri = vi;
    return true;
}

/* Multiply (vr, vi) by (1 + sign psi(s) e): the first-order correction for an
 * argument s of Gamma that was rounded from s + e (both parts). */
static void psi_correct(double* vr, double* vi, double sr, double si,
                        double er, double ei, double sign) {
    if (er == 0.0 && ei == 0.0) return;
    double pr, pi;
    if (!digamma_c(sr, si, &pr, &pi)) return;
    double cr, ci; cx_mul(pr, pi, er, ei, &cr, &ci);
    cx_mul(*vr, *vi, 1.0 + sign * cr, sign * ci, vr, vi);
}

/* Beta(a, b) = Gamma(a) Gamma(b) / Gamma(a + b), complex. */
bool sfg_beta_c(double ar, double ai, double br, double bi, double* rr, double* ri) {
    if (ai == 0.0 && bi == 0.0) {
        double v; if (!sfg_beta(ar, br, &v)) return false;
        *rr = v; *ri = 0.0; return true;
    }
    if (!isfinite(ar) || !isfinite(ai) || !isfinite(br) || !isfinite(bi)) return false;
    double sr = ar + br, si = ai + bi;
    double q[2] = { br, bi };
    double vr, vi;
    if (!gamma_ratio_c(ar, ai, q, sr, si, &vr, &vi)) return false;
    psi_correct(&vr, &vi, sr, si, two_sum_err(ar, br, sr), two_sum_err(ai, bi, si), -1.0);
    *rr = vr; *ri = vi;
    return isfinite(vr) && isfinite(vi);
}

/* ------------------------------------------------------------------ */
/* Pochhammer                                                         */
/* ------------------------------------------------------------------ */

#define SFG_POCH_PRODUCT_MAX 256

bool sfg_pochhammer(double a, double n, double* out) {
    if (!isfinite(a) || !isfinite(n)) return false;
    if (n == 0.0) { *out = 1.0; return true; }
    if (n == floor(n) && fabs(n) <= SFG_POCH_PRODUCT_MAX) {
        int k = (int)n;
        double v = 1.0;
        if (k > 0) {
            for (int j = 0; j < k; j++) v *= a + (double)j;
        } else {
            /* (a)_{-k} = 1 / ((a-1)(a-2)...(a-k)) */
            for (int j = 1; j <= -k; j++) v *= a - (double)j;
            if (v == 0.0) return false;              /* pole: ComplexInfinity */
            v = 1.0 / v;
        }
        *out = v;
        return isfinite(v);
    }
    /* Gamma(a + n) / Gamma(a) */
    if (nonpos_int(a)) return false;
    double s = a + n;
    if (nonpos_int(s)) return false;
    if (fabs(a) > 170.0 || fabs(s) > 170.0) return false;
    double v = tgamma(s) / tgamma(a);
    double e = two_sum_err(a, n, s);
    if (e != 0.0) {
        double ps;
        if (sfg_digamma(s, &ps)) v *= 1.0 + ps * e;
    }
    *out = v;
    return isfinite(v) && v != 0.0;
}

bool sfg_pochhammer_c(double ar, double ai, double nr, double ni, double* rr, double* ri) {
    if (ai == 0.0 && ni == 0.0) {
        double v; if (!sfg_pochhammer(ar, nr, &v)) return false;
        *rr = v; *ri = 0.0; return true;
    }
    if (!isfinite(ar) || !isfinite(ai) || !isfinite(nr) || !isfinite(ni)) return false;
    if (ni == 0.0 && nr == floor(nr) && fabs(nr) <= SFG_POCH_PRODUCT_MAX) {
        int k = (int)nr;
        double vr = 1.0, vi = 0.0;
        if (k >= 0) {
            for (int j = 0; j < k; j++) cx_mul(vr, vi, ar + (double)j, ai, &vr, &vi);
        } else {
            for (int j = 1; j <= -k; j++) cx_mul(vr, vi, ar - (double)j, ai, &vr, &vi);
            if (vr == 0.0 && vi == 0.0) return false;
            cx_recip(vr, vi, &vr, &vi);
        }
        *rr = vr; *ri = vi;
        return isfinite(vr) && isfinite(vi);
    }
    /* Gamma(a + n) / Gamma(a), with the rounding of a + n corrected. */
    double sr = ar + nr, si = ai + ni;
    double vr, vi;
    if (!gamma_ratio_c(sr, si, NULL, ar, ai, &vr, &vi)) return false;
    psi_correct(&vr, &vi, sr, si, two_sum_err(ar, nr, sr), two_sum_err(ai, ni, si), 1.0);
    *rr = vr; *ri = vi;
    return isfinite(vr) && isfinite(vi);
}
