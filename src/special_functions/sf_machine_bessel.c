/* 1/Gamma(z) = sum_{k>=1} c_k z^k (DLMF 5.7.1); RG[k] = c_{k+1}, so
 * 1/Gamma(1 + x) = sum_{k>=0} RG[k] x^k. For |x| <= 1/2 the 28 terms reach
 * 1e-26. */
static const double RG[28] = {
    1.00000000000000000e+00,  5.77215664901532866e-01, -6.55878071520253902e-01,
   -4.20026350340952370e-02,  1.66538611382291479e-01, -4.21977345555443334e-02,
   -9.62197152787697303e-03,  7.21894324666309990e-03, -1.16516759185906517e-03,
   -2.15241674114950975e-04,  1.28050282388116196e-04, -2.01348547807882387e-05,
   -1.25049348214267063e-06,  1.13302723198169593e-06, -2.05633841697760707e-07,
    6.11609510448141609e-09,  5.00200764446922295e-09, -1.18127457048702004e-09,
    1.04342671169110054e-10,  7.78226343990507081e-12, -3.69680561864220598e-12,
    5.10037028745447575e-13, -2.05832605356650664e-14, -5.34812253942301782e-15,
    1.22677862823826084e-15, -1.18125930169745883e-16,  1.18669225475160037e-18,
    1.41238065531803186e-18
};

/* Temme's gamma_1, gamma_2 and 1/Gamma(1 +- mu), |mu| <= 1/2:
 *   gam1 = (1/Gamma(1-mu) - 1/Gamma(1+mu)) / (2 mu),
 *   gam2 = (1/Gamma(1-mu) + 1/Gamma(1+mu)) / 2,
 * from the odd and even halves of the 1/Gamma(1+x) series, so gam1 suffers
 * no cancellation as mu -> 0. */
static void temme_gammas(double mu, double* g1, double* g2, double* gpl, double* gmi) {
    double m2 = mu * mu, e = 0.0, o = 0.0;
    for (int k = 26; k >= 0; k -= 2) e = e * m2 + RG[k];
    for (int k = 27; k >= 1; k -= 2) o = o * m2 + RG[k];
    *g2 = e;
    *g1 = -o;
    *gpl = e + mu * o;          /* 1/Gamma(1+mu) */
    *gmi = e - mu * o;          /* 1/Gamma(1-mu) */
}

/* Temme's series for K_mu(z), K_{mu+1}(z), |mu| <= 1/2, |z| <= 2
 * (the complex form of Numerical Recipes' bessik small-x branch). */
static bool temme_k(double mu, cx z, cx* kmu, cx* kmu1) {
    cx x2 = cscal(z, 0.5);
    double pimu = M_PI * mu;
    double fact = (mu == 0.0) ? 1.0 : pimu / sin(pimu);
    cx d = cneg(clogz(x2));
    cx e = cscal(d, mu);
    cx fact2;                                       /* sinh(e)/e */
    if (cnorm1(e) < 1e-3) {
        cx e2 = cmul(e, e);
        fact2 = cadd(cxm(1.0, 0.0),
                     cmul(e2, cadd(cxm(1.0 / 6.0, 0.0),
                                   cmul(e2, cadd(cxm(1.0 / 120.0, 0.0),
                                                 cscal(e2, 1.0 / 5040.0))))));
    } else {
        double ch = cosh(e.re), sh = sinh(e.re), c = cos(e.im), s = sin(e.im);
        fact2 = cdiv(cxm(sh * c, ch * s), e);
    }
    double g1, g2, gpl, gmi;
    temme_gammas(mu, &g1, &g2, &gpl, &gmi);
    cx coshe;
    {
        double ch = cosh(e.re), sh = sinh(e.re);
        coshe = cxm(ch * cos(e.im), sh * sin(e.im));
    }
    cx ff = cscal(cadd(cscal(coshe, g1), cmul(cscal(fact2, g2), d)), fact);
    cx sum = ff;
    cx ee = cexpz(e);                               /* (z/2)^-mu */
    cx p = cscal(ee, 0.5 / gpl);
    cx q = cscal(cinv(ee), 0.5 / gmi);
    cx c = cxm(1.0, 0.0);
    cx dd = cmul(x2, x2);
    cx sum1 = p;
    int i;
    for (i = 1; i <= 500; i++) {
        double di = (double)i;
        ff = cscal(cadd(cadd(cscal(ff, di), p), q), 1.0 / (di * di - mu * mu));
        c = cscal(cmul(c, dd), 1.0 / di);
        p = cscal(p, 1.0 / (di - mu));
        q = cscal(q, 1.0 / (di + mu));
        cx del = cmul(c, ff);
        sum = cadd(sum, del);
        cx del1 = cmul(c, csub(p, cscal(ff, di)));
        sum1 = cadd(sum1, del1);
        if (cnorm1(del) < cnorm1(sum) * BS_EPS && cnorm1(del1) < cnorm1(sum1) * BS_EPS)
            break;
    }
    if (i > 500) return false;
    *kmu = sum;
    *kmu1 = cdiv(sum1, x2);
    return cfinite(*kmu) && cfinite(*kmu1);
}

/* Steed's algorithm for CF2: K_mu(z), K_{mu+1}(z), |mu| <= 1/2, Re z >= 0,
 * |z| > 2 (Thompson & Barnett 1987; NR bessik large-x branch, complex). */
static bool steed_k(double mu, cx z, cx* kmu, cx* kmu1) {
    double a1 = 0.25 - mu * mu;
    cx b = cscal(cadd(z, cxm(1.0, 0.0)), 2.0);
    cx d = cinv(b);
    cx delh = d, h = d;
    cx q1 = cxm(0.0, 0.0), q2 = cxm(1.0, 0.0);
    double c = a1;
    cx q = cxm(a1, 0.0);
    double a = -a1;
    cx s = cadd(cxm(1.0, 0.0), cscal(delh, a1));
    int i;
    for (i = 2; i <= 20000; i++) {
        a -= 2.0 * (double)(i - 1);
        c = -a * c / (double)i;
        cx qnew = cscal(csub(q1, cmul(b, q2)), 1.0 / a);
        q1 = q2; q2 = qnew;
        q = cadd(q, cscal(qnew, c));
        b = cadd(b, cxm(2.0, 0.0));
        d = cinv(cadd(b, cscal(d, a)));
        delh = cmul(csub(cmul(b, d), cxm(1.0, 0.0)), delh);
        h = cadd(h, delh);
        cx dels = cmul(q, delh);
        s = cadd(s, dels);
        if (cnorm1(dels) < cnorm1(s) * BS_EPS) break;
    }
    if (i > 20000) return false;
    h = cscal(h, a1);
    cx pre = cmul(csqrtz(cscal(cinv(z), M_PI / 2.0)), cexpz(cneg(z)));
    if (!(cnorm1(pre) >= DBL_MIN)) return false;   /* e^-z underflowed */
    *kmu = cdiv(pre, s);
    *kmu1 = cdiv(cmul(*kmu, csub(cadd(cxm(mu + 0.5, 0.0), z), h)), z);
    return cfinite(*kmu) && cfinite(*kmu1);
}

/* I_{nu+1}(z) / I_nu(z), nu > -1, by CF1 = 1/(b1 + 1/(b2 + ...)),
 * b_k = 2 (nu + k)/z, evaluated with the modified Lentz method. */
static bool cf1_ratio(double nu, cx z, cx* out) {
    const double tiny = 1e-300;
    cx zi2 = cscal(cinv(z), 2.0);
    cx f = cxm(tiny, 0.0), C = f, D = cxm(0.0, 0.0);
    int k;
    for (k = 1; k <= 100000; k++) {
        cx b = cscal(zi2, nu + (double)k);
        D = cadd(b, D);
        if (cnorm1(D) == 0.0) D = cxm(tiny, 0.0);
        D = cinv(D);
        C = cadd(b, cinv(C));
        if (cnorm1(C) == 0.0) C = cxm(tiny, 0.0);
        cx del = cmul(C, D);
        f = cmul(f, del);
        if (fabs(del.re - 1.0) + fabs(del.im) < BS_EPS) break;
    }
    if (k > 100000) return false;
    *out = f;
    return cfinite(f);
}

/* (z/2)^nu / Gamma(nu + 1), nu > -1. */
static cx i_lead(double nu, cx x2) {
    if (nu == 0.0) return cxm(1.0, 0.0);
    if (nu == floor(nu) && nu <= 64.0) {             /* exact-ish integer power */
        cx p = cxm(1.0, 0.0), b = x2;
        unsigned n = (unsigned)nu;
        double g = 1.0;
        for (unsigned k = 2; k <= n; k++) g *= (double)k;
        while (n) { if (n & 1u) p = cmul(p, b); b = cmul(b, b); n >>= 1; }
        return cscal(p, 1.0 / g);
    }
    cx l = cscal(clogz(x2), nu);
    l.re -= lgamma(nu + 1.0);
    return cexpz(l);                                 /* Gamma(nu+1) > 0 for nu > -1 */
}

/* Ascending series I_nu(z) = sum (z/2)^{2k+nu} / (k! Gamma(nu+k+1)). */
static bool i_series(double nu, cx z, cx* out) {
    cx x2 = cscal(z, 0.5);
    cx t = i_lead(nu, x2);
    cx q = cmul(x2, x2);
    cx sum = t;
    int k;
    for (k = 1; k <= 1000; k++) {
        t = cscal(cmul(t, q), 1.0 / ((double)k * ((double)k + nu)));
        sum = cadd(sum, t);
        if (cnorm1(t) <= cnorm1(sum) * BS_EPS) break;
    }
    if (k > 1000) return false;
    *out = sum;
    return cfinite(sum);
}

/* Hankel's expansions (DLMF 10.40.2 / 10.40.5) for K_nu and (if want_i) I_nu,
 * Re z >= 0, Im z >= 0. Returns false unless the series reaches BS_EPS
 * before its terms turn. */
static bool hankel_ik(double nu, cx z, bool want_i, cx* I, cx* K) {
    double mu4 = 4.0 * nu * nu;
    cx zinv = cinv(z);
    cx t = cxm(1.0, 0.0), sk = t, si = t;
    double prev = 1.0;
    bool conv = false;
    for (int k = 1; k <= 80; k++) {
        double tk = (double)(2 * k - 1);
        double num = (mu4 - tk * tk) / (8.0 * (double)k);
        if (num == 0.0) { conv = true; break; }      /* half-integer order: exact */
        t = cscal(cmul(t, zinv), num);
        double at = cnorm1(t);
        if (at > prev) break;                         /* the series has turned */
        prev = at;
        sk = cadd(sk, t);
        si = (k & 1) ? csub(si, t) : cadd(si, t);
        if (at < BS_EPS * fmin(cnorm1(sk), cnorm1(si))) { conv = true; break; }
    }
    if (!conv) return false;
    cx sq = csqrtz(z);
    cx em = cexpz(cneg(z));
    if (!(cnorm1(em) >= DBL_MIN)) return false;
    *K = cdiv(cscal(cmul(em, sk), 1.2533141373155003), sq);          /* sqrt(pi/2) */
    if (want_i) {
        cx ep = cexpz(z);
        if (!cfinite(ep)) return false;
        cx v = cdiv(cscal(cmul(ep, si), 0.3989422804014327), sq);    /* 1/sqrt(2 pi) */
        if (z.im > 0.0) {
            /* + i e^{i nu pi} e^{-z} / sqrt(2 pi z) sum a_k / z^k */
            cx w = cdiv(cscal(cmul(em, sk), 0.3989422804014327), sq);
            v = cadd(v, cmuli(cmul(cispi(nu), w)));
        }
        *I = v;
    }
    return cfinite(*K);
}

#define NEED_I 1
#define NEED_1 2      /* also the nu+1 values */

/* I_nu, K_nu (and with NEED_1 also I_{nu+1}, K_{nu+1}) for real nu >= -1/2
 * and z in the closed first quadrant, z != 0. */
static bool ik_q1(double nu, cx z, int need, cx* Iv, cx* Kv, cx* I1, cx* K1) {
    double r = hypot(z.re, z.im);
    if (!(r > 0.0) || !isfinite(r) || nu > BS_MAXNU) return false;

    if (r >= BS_HANKEL_R && nu * nu < r) {
        cx a = cxm(0.0, 0.0), b = a, c = a, d = a;
        bool ok = hankel_ik(nu, z, need & NEED_I, &a, &b);
        if (ok && (need & NEED_1)) ok = hankel_ik(nu + 1.0, z, need & NEED_I, &c, &d);
        if (ok) { *Iv = a; *Kv = b; *I1 = c; *K1 = d; return true; }
    }

    int n = (int)floor(nu + 0.5);
    double mu = nu - (double)n;
    cx km, km1;
    if (!(r <= BS_TEMME_R ? temme_k(mu, z, &km, &km1) : steed_k(mu, z, &km, &km1)))
        return false;
    if (n > 0) {
        cx zi2 = cscal(cinv(z), 2.0);
        for (int k = 1; k <= n; k++) {
            cx kn = cadd(km, cmul(cscal(zi2, mu + (double)k), km1));
            km = km1; km1 = kn;
            if (!cfinite(km1)) return false;
        }
    }
    *Kv = km; *K1 = km1;

    if (need & NEED_I) {
        if (r * r <= 4.0 * (nu + 1.0)) {
            if (!i_series(nu, z, Iv)) return false;
            if (need & NEED_1) { if (!i_series(nu + 1.0, z, I1)) return false; }
        } else {
            cx f;
            if (!cf1_ratio(nu, z, &f)) return false;
            *Iv = cinv(cmul(z, cadd(km1, cmul(f, km))));
            *I1 = cmul(f, *Iv);
        }
        if (!cfinite(*Iv)) return false;
    }
    return true;
}

/* As ik_q1, for any z with Re z >= 0 (conjugate symmetry for Im z < 0). */
static bool ik_rhp(double nu, cx z, int need, cx* Iv, cx* Kv, cx* I1, cx* K1) {
    if (z.im < 0.0) {
        if (!ik_q1(nu, cconj(z), need, Iv, Kv, I1, K1)) return false;
        *Iv = cconj(*Iv); *Kv = cconj(*Kv); *I1 = cconj(*I1); *K1 = cconj(*K1);
        return true;
    }
    return ik_q1(nu, z, need, Iv, Kv, I1, K1);
}

/* I_nu(z) and K_nu(z) for ANY real nu, Re z >= 0. */
static bool ik_any_rhp(double nu, cx z, bool want_k, cx* I, cx* K) {
    double na = fabs(nu);
    cx Iv, Kv, I1, K1;
    if (!ik_rhp(na, z, NEED_I, &Iv, &Kv, &I1, &K1)) return false;
    (void)want_k;
    if (nu < 0.0 && nu != floor(nu)) {
        double s, c; sincospi(na, &s, &c);
        Iv = cadd(Iv, cscal(Kv, 2.0 / M_PI * s));
    }
    *I = Iv; *K = Kv;
    return true;
}

