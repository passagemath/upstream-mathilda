/* c0h + (c0l + u * Q(u)) for a table row of degree `deg` (c_deg .. c_1, c0h, c0l). */
static inline double tpoly(const double* c, int deg, double u) {
    double q;
    switch (deg) {
        case 6:  q = estrin6(c, u);  break;
        case 7:  q = estrin7(c, u);  break;
        case 10: q = estrin10(c, u); break;
        case 11: q = estrin11(c, u); break;
        case 12: q = estrin12(c, u); break;
        case 13: q = estrin13(c, u); break;
        default: q = estrin14(c, u); break;
    }
    return c[deg] + (c[deg + 1] + q * u);
}

/* sin(pi s/2) and cos(pi s/2) for |s| <= 1/2 (angle within pi/4): minimax-
 * class polynomials in s^2, no argument multiplication by pi/2 to round. */
static inline void sincos_halfpi(double s, double* sn, double* cs) {
    double t = s * s;
    double u = (t - SINHP_T_MID) * SINHP_T_IHALF;
    *sn = s * tpoly(SINHP_T[0], 6, u);
    *cs = tpoly(COSHP_T[0], 7, u);
}

/* Nearest integer (ties to even) for |a| < 2^51 without a libm call:
 * nearbyint/floor are function calls on x86-64 when the build does not target
 * SSE4.1, which costs more than the polynomials around them. Needs
 * round-to-nearest and no -ffast-math reassociation (both hold here). */
static inline double rint_small(double a) {
    const double M = 6755399441055744.0;   /* 1.5 * 2^52 */
    return (a + M) - M;
}

/* An integer-valued a modulo 4, in {0, 1, 2, 3}; exact for every double. */
static inline double mod4(double a) {
    if (fabs(a) >= 2251799813685248.0) {   /* 2^51: rare, leave it to libm */
        double q = fmod(a, 4.0);
        return q < 0.0 ? q + 4.0 : q;
    }
    double q = a - 4.0 * rint_small(0.25 * a);  /* in [-2, 2] */
    return q < 0.0 ? q + 4.0 : q;
}

/* Rotate (sin a, cos a) by q quarter turns (q in 0..3). */
static inline void quarter_turn(double q, double sa, double ca, double* s, double* c) {
    if (q == 0.0)      { *s =  sa; *c =  ca; }
    else if (q == 1.0) { *s =  ca; *c = -sa; }
    else if (q == 2.0) { *s = -sa; *c = -ca; }
    else               { *s = -ca; *c =  sa; }
}

/* sin and cos of a radian angle a = ah + al >= 0. Cody-Waite reduction by
 * pi/2 in three 33-bit pieces (k*piece exact for k < 2^20), then the half-pi
 * kernels on s = r * 2/pi. Larger angles go to libm. */
static void sincos_rad(double ah, double al, double* s, double* c) {
    if (!(ah < 1.0e6)) {
        double sa = sin(ah), ca = cos(ah);
        *s = sa + al * ca;
        *c = ca - al * sa;
        return;
    }
    double k = rint_small(ah * TWO_OVER_PI);
    double r = ((ah - k * PIO2_1) - k * PIO2_2) - k * PIO2_3 + al;
    if (fabs(r) < 1e-6 && k != 0.0) {       /* hard case: within 1e-6 of k pi/2 */
        double sa = sin(ah), ca = cos(ah);   /* three-piece pi/2 is short there */
        *s = sa + al * ca;
        *c = ca - al * sa;
        return;
    }
    double sa, ca;
    sincos_halfpi(r * TWO_OVER_PI, &sa, &ca);
    quarter_turn(mod4(k), sa, ca, s, c);
}

/* sin and cos of (pi/2) t for a double-double t = th + tl >= 0, reduced
 * EXACTLY: th - k for the nearest integer k is exact, so (pi/2)(t mod 4)
 * costs no rounding at all (the phase of the Fresnel integrals, and of erf
 * at the rotated Fresnel arguments). */
static void sincos_halfpi_dd(double th, double tl, double* s, double* c) {
    double k = (th < 2251799813685248.0) ? rint_small(th) : th;
    double r = (th - k) + tl;               /* th - k exact */
    double q = mod4(k);
    if (fabs(r) > 0.5) {                    /* th >= 2^53: tl itself is large */
        double k2 = rint_small(r);
        r -= k2;
        q = mod4(q + k2);
    }
    double sa, ca;
    sincos_halfpi(r, &sa, &ca);
    quarter_turn(q, sa, ca, s, c);
}

/* ---------------------------------------------------------------------
 * Real erf and erfc.
 *   |x| < 1/2     erf = (2/sqrt(pi)) x sum_k (-1)^k x^{2k}/(k!(2k+1))  (13 terms)
 *   1/2 <= x < 6  erfc = e^{-x^2} erfcx(x), erfcx from the 0.5-wide table
 *   6 <= x        erfc = e^{-x^2} (1/x) P(1/x^2)  (ERFCX2_T, x <= 27.39)
 *   x < 0         erfc = 2 - erfc(-x), erf odd
 * e^{-x^2} comes from the double-double square (no x^2 ulps of exponent
 * error), so erfc carries ~1.5 ulp where the platform libm measured up to
 * 5 ulps (macOS, 1.5 <= x <= 26); and it costs one exp, not libm's two.
 * erf = 1 - erfc for x >= 1/2 (erfc <= 0.48 there: no cancellation). */
static inline double erfcx_tab(double X) {
    int i = (int)((X - 0.5) * 2.0);
    double mid = 0.75 + 0.5 * i;
    return tpoly(ERFCX_T[i], 13, (X - mid) * 4.0);
}

static inline double erf_small(double X) {        /* |X| < 1/2 */
    double t = X * X, p = ERF_MAC_R[12];
    for (int k = 11; k >= 0; k--) p = p * t + ERF_MAC_R[k];
    return TWO_OVER_SQRTPI * X * p;
}

#define EXP_M700 9.8596765437597708567e-305      /* e^{-700} */

/* erfc(X) for X >= 1/2, given emx2 = e^{-X^2} (the callers already have it,
 * or pass a negative value to have it formed here). */
static double erfc_tail(double X, double emx2) {
    if (X < 6.0) {
        if (emx2 < 0.0) { double h, l; dd_mul(X, X, &h, &l); emx2 = exp_dd(-h, -l); }
        return emx2 * erfcx_tab(X);
    }
    if (X >= 27.4) return 0.0;                 /* below half the least subnormal */
    double h, l, t = 1.0 / (X * X);
    dd_mul(X, X, &h, &l);
    double gx = tpoly(ERFCX2_T[0], 10, (t - ERFCX2_T_MID) * ERFCX2_T_IHALF) / X;
    if (h <= 700.0) return (emx2 >= 0.0 ? emx2 : exp_dd(-h, -l)) * gx;
    return (exp_dd(700.0 - h, -l) * gx) * EXP_M700;   /* one rounding into the subnormals */
}

bool sf_erfc_r(double x, double* out) {
    double X = fabs(x), v;
    if (isnan(x)) return false;
    if (X < 0.5)          v = 1.0 - (x < 0.0 ? -erf_small(X) : erf_small(X));
    else if (x > 0.0)     v = erfc_tail(X, -1.0);
    else                  v = 2.0 - erfc_tail(X, -1.0);
    *out = v;
    return true;
}

bool sf_erf_r(double x, double* out) {
    double X = fabs(x), v;
    if (isnan(x)) return false;
    v = (X < 0.5) ? erf_small(X) : 1.0 - erfc_tail(X, -1.0);
    *out = (x < 0.0) ? -v : v;
    return true;
}

/* erf(X), erfc(X) for X >= 0 when e^{-X^2} is already known. */
static double erf_real_fast(double X, double emx2) {
    return (X < 0.5) ? erf_small(X) : 1.0 - erfc_tail(X, emx2);
}

static double erfc_real_fast(double X, double emx2) {
    return (X < 0.5) ? 1.0 - erf_small(X) : erfc_tail(X, emx2);
}

/* =====================================================================
 * 2. Complex erf -- Salzer's series
 * =====================================================================
 * H. E. Salzer, "Formulas for calculating the error function of a complex
 * variable", Math. Tables Aids Comput. 5 (1951) 67-70; Abramowitz & Stegun
 * 7.1.29. For X >= 0, Y >= 0:
 *
 *   erf(X + iY) = erf(X)
 *       + e^{-X^2}/(2 pi X) [(1 - cos 2XY) + i sin 2XY]
 *       + (2/pi) e^{-X^2} sum_{n>=1} e^{-n^2/4}/(n^2 + 4X^2) [f_n + i g_n]
 *   f_n = 2X - 2X cosh(nY) cos(2XY) + n sinh(nY) sin(2XY)
 *   g_n = 2X cosh(nY) sin(2XY) + n sinh(nY) cos(2XY).
 *
 * Derivation (so the error term is known rather than quoted): erf(X+iY) -
 * erf(X) = (2i/sqrt(pi)) e^{-X^2} int_0^Y e^{s^2} e^{-2iXs} ds, and
 * e^{s^2} = (1/(2 sqrt(pi))) int e^{-u^2/4 + us} du. Replacing the u-integral
 * by the trapezoidal sum at u = n gives the series; by Poisson summation the
 * relative error of that sum is 2 e^{-4 pi^2} = 1.4e-17 for every real s, so
 * the truncation is a fraction of an ulp throughout -- the formula is not an
 * approximation of limited accuracy but an exponentially convergent one.
 *
 * Three properties make it the right machine kernel:
 *   - Every term is real arithmetic on erf(X), e^{-X^2}, sin/cos(XY) and
 *     cosh/sinh(nY); no complex division, no continued fraction.
 *   - n runs to about 2Y + 13 (the Gaussian e^{-(n/2 - Y)^2} relative to its
 *     peak falls below 2^-60), so the work grows only linearly in |y|.
 *   - It has no cancellation in the dominant terms: they combine as
 *     (sin + i cos)(2 SS + 4iX SC) with SS, SC sums of positive terms, so the
 *     result's modulus is never smaller than the pieces it is built from.
 *     The one cancellation-prone piece, 2X(1 - cosh(nY) cos 2XY) for small
 *     nY and XY, is rewritten with 1 - cos = 2 sin^2 and
 *     cosh - 1 = sinh^2/(cosh + 1).
 *
 * The caller passes X, Y >= 0 and the transcendental pieces computed
 * ACCURATELY from double-double squares and products (see ErfArgs).
 * Two regimes for the cosh/sinh(nY) factors:
 *   Y <= SALZER_YS : the hyperbolic rotation recurrence from cosh Y, sinh Y.
 *       The weight e^{-n^2/4} cosh(nY) peaks at n ~ 2Y <= 3, so the n*eps
 *       growth of the recurrence never reaches a term that matters.
 *   Y >  SALZER_YS : the scaled Gaussian P_n = e^{-(n/2 - Y)^2} (and its
 *       mirror Q_n = e^{-(n/2 + Y)^2}), so that e^{-n^2/4} cosh(nY) =
 *       e^{Y^2} (P_n + Q_n)/2 and the factor e^{Y^2 - X^2} is applied once.
 *       P_n is generated OUTWARD from its peak n0 ~ 2Y in both directions, so
 *       the recurrence's rounding grows only where the weights are already
 *       negligible -- the naive recurrence from n = 1 reached the peak with
 *       ~2Y^2 ulps of accumulated error.
 */

