/* sf_machine_gamma.c -- raw-double kernels for the Gamma family.
 *
 *   Gamma, LogGamma            complex z (the real axis stays on libm tgamma/lgamma)
 *   PolyGamma[n, z]            real and complex z, integer order n
 *   Beta[a, b], Pochhammer     real and complex
 *
 * Every function here is the single machine implementation shared by the
 * scalar builtin, the NDArray / packed element-wise kernels (ndkernels.c) and the
 * Compile[] VM; see sf_machine_gamma.h for the contract.
 *
 * Algorithms (all classical; references in each section):
 *
 *   digamma, real   x in [1,2]: a degree-22 Chebyshev interpolant of
 *                   psi(x)/(x - x0) times (x - x0), x0 = 1.4616... the positive
 *                   zero carried as a double-double, so the answer is RELATIVELY
 *                   accurate right through the zero (the technique of Cody,
 *                   Strecok & Thacher, Math. Comp. 27 (1973), and of Boost's
 *                   digamma).  x in (0,1) and (2,10): psi(x+1) = psi(x) + 1/x,
 *                   whose shifts by an integer are exact in double.  x >= 10: the
 *                   asymptotic series (DLMF 5.11.2).  x < 0: the reflection
 *                   psi(1-x) - psi(x) = pi cot(pi x) (DLMF 5.5.4), with the cotangent
 *                   argument reduced exactly.
 *   polygamma n>=1  upward recurrence psi^(n)(z+1) = psi^(n)(z) + (-1)^n n!/z^(n+1)
 *                   (DLMF 5.15.5) until Re z is large, then the asymptotic series
 *                   psi^(n)(z) ~ (-1)^(n+1) [ (n-1)!/z^n + n!/(2 z^(n+1))
 *                   + sum_k B_2k (2k+n-1)!/((2k)! z^(2k+n)) ]  (DLMF 5.15.8).
 *                   On the real axis every recurrence term has one sign, so the
 *                   sum loses nothing to cancellation.
 *   Taylor tiles    near the real axis (-5 <= Re z < 10, |Im z| < 19/4) lnGamma
 *                   and psi come from precomputed Taylor series about 30 centres
 *                   {1.25, 1.75, 2.25} + {0, 1/2, ..., 9/2} i (coefficients: the
 *                   polygamma values at the centre, DLMF 5.7 / 5.15), the
 *                   argument moved into the strip 1 <= Re < 5/2 by the exact
 *                   recurrence. Both real zeros of lnGamma and psi's lie INSIDE
 *                   the strip -- never across a recurrence step, which would
 *                   cancel -- and on the real row lnGamma's series is for
 *                   lnGamma / ((z-1)(z-2)), carrying both zeros exactly. Shifting
 *                   to Stirling instead forms lnGamma as a difference of O(10)
 *                   numbers, up to 2^6 above the answer.
 *   digamma, cplx   tiles; a Taylor series about the zero x0 for |z - x0| <= 0.35;
 *                   elsewhere the recurrence to Re z >= 10 and the asymptotic
 *                   series (DLMF 5.11.2); reflection (DLMF 5.5.4) for Re z < -5.
 *   lnGamma, cplx   tiles; elsewhere Stirling's series (DLMF 5.11.1) after shifting
 *                   Re z >= 7 by lnGamma(z) = lnGamma(z+N) - sum_j log(z+j). The
 *                   sum of the N principal logs is formed as ONE log of the
 *                   product, the 2 pi i windings being counted as the running
 *                   product crosses the negative real axis -- exactly the
 *                   continuous branch (Hare 1997, J. Symbolic Comp. 23) that
 *                   Mathematica uses, analytic off the negative real axis and
 *                   equal to Log[Gamma[x]] for x > 0.
 *   Gamma, cplx     exp of the same, once: Gamma(z) = exp(E) * P^(+-1), with E
 *                   carried as a double-double (the tile constant term; Dekker
 *                   products and an extra-precise log|w| in Stirling), because
 *                   exp turns E's ABSOLUTE error into Gamma's relative error.
 *   Beta            real: tgamma ratio, with the rounding of a + b corrected to
 *                   first order through psi (a + b is not representable in
 *                   general, and Gamma amplifies that rounding by psi(a+b)).
 *                   complex: the three Gammas under ONE exponential (their
 *                   double-double exponents summed), the same psi correction.
 *   Pochhammer      integer n: the product a (a+1) ... (a+n-1) (or its reciprocal
 *                   counterpart for n < 0), real or complex; otherwise the Gamma
 *                   ratio, as for Beta.
 *
 * Complex arithmetic is written out on (re, im) pairs (no <complex.h>).
 */
