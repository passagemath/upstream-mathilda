#!/usr/bin/env python3
"""Generate src/strings/named_chars.inc -- the \\[Name] -> code point table used
by the string-literal lexer (utf8.c: u8_named_char).

Usage: tools/gen_named_chars.py <UnicodeCharacters.tr> > src/strings/named_chars.inc

The input is Mathematica's FrontEnd/TextResources/UnicodeCharacters.tr; each
data line is `0xHHHH <tab><tab> \\[Name] ...`. Output entries are sorted by
name in strcmp (byte) order, as u8_named_char's binary search requires."""
import re, sys

entries = {}
for line in open(sys.argv[1], encoding="utf-8", errors="replace"):
    m = re.match(r"0x([0-9A-Fa-f]+)\s+\\\[([A-Za-z0-9]+)\]", line)
    if m:
        entries.setdefault(m.group(2), int(m.group(1), 16))

print("/* Generated by tools/gen_named_chars.py -- do not edit. */")
for name in sorted(entries, key=lambda s: s.encode()):
    print(f'    {{"{name}", 0x{entries[name]:04X}u}},')
