/* PolyGamma, complex                                                 */
/* ------------------------------------------------------------------ */

/* psi(w), Re w >= 10: log w - 1/(2w) - sum_{k=1}^{12} B_2k/(2k) w^-2k. */
static void dig_asym_c(double wr, double wi, double* outr, double* outi) {
    double ir, ii; cx_recip(wr, wi, &ir, &ii);
    double zr, zi; cx_mul(ir, ii, ir, ii, &zr, &zi);
    double pr, pi; poly4_rc(SFG_DIGAMMA_ASY, 12, zr, zi, &pr, &pi);
    cx_mul(pr, pi, zr, zi, &pr, &pi);
    double lr, li; cx_log(wr, wi, &lr, &li);
    *outr = lr - 0.5 * ir - pr;
    *outi = li - 0.5 * ii - pi;
}

/* pi cot(pi z), z = x + i y, with the real part reduced exactly.  Written as
 * (sin a cos a - i sinh b cosh b) / (sin^2 a + sinh^2 b), a = pi r, b = pi y:
 * the denominator is a sum of squares, so nothing cancels near the poles. */
static bool pi_cot_c(double x, double y, double* rr, double* ri) {
    double fl = floor(x);
    double r = x - fl;
    if (r > 0.5) r -= 1.0;
    double a = M_PI * r, b = M_PI * y;
    double sa = sin(a), ca = cos(a);
    if (fabs(b) > 20.0) {                        /* coth(b) = sign(b) to 2^-57 */
        double e = exp(-2.0 * fabs(b));
        *rr = M_PI * 4.0 * sa * ca * e;
        *ri = -M_PI * (b > 0 ? 1.0 : -1.0);
        return true;
    }
    double sb = sinh(b), cb = cosh(b);
    double d = sa * sa + sb * sb;
    if (!(d > 0.0)) return false;                /* exactly at a pole */
    *rr = M_PI * sa * ca / d;
    *ri = -M_PI * sb * cb / d;
    return true;
}

/* psi(z) for Im z > 0 (the caller conjugates for Im z < 0). */
static bool digamma_upper(double zr, double zi, double* outr, double* outi) {
    /* The zero x0 = 1.4616...: a Taylor series about it (radius of convergence
     * x0, the distance to the pole at 0), |z - x0| <= 0.35 so 28 terms reach
     * 2^-57, keeping the answer relatively accurate where psi(z+1) - 1/z would
     * cancel. */
    double dr = (zr - SFG_X0_HI) - SFG_X0_LO;
    if (dr * dr + zi * zi <= 0.1225) {
        double pr, pi; poly4_rc(SFG_PSI_ROOT, 28, dr, zi, &pr, &pi);
        cx_mul(pr, pi, dr, zi, outr, outi);
        return true;
    }
    double fr, fi; int m;
    if (tile_eval(1, zr, zi, &fr, &fi, NULL, NULL, &m)) {
        double sr = 0.0, si = 0.0;
        if (m > 0) {
            /* psi(z) = psi(z - m) + sum_{j=1}^{m} 1/(z - j), smallest first */
            for (int j = 1; j <= m; j++) {
                double ir, ii; cx_recip(zr - (double)j, zi, &ir, &ii);
                sr += ir; si += ii;
            }
        } else if (m < 0) {
            /* psi(z) = psi(z - m) - sum_{j=0}^{-m-1} 1/(z + j) */
            for (int j = -m - 1; j >= 0; j--) {
                double ir, ii; cx_recip(zr + (double)j, zi, &ir, &ii);
                sr -= ir; si -= ii;
            }
        }
        *outr = fr + sr; *outi = fi + si;
        return isfinite(*outr) && isfinite(*outi);
    }
    if (zr < 0.0) {
        /* psi(z) = psi(1 - z) - pi cot(pi z)  (DLMF 5.5.4); 1 - z has Im < 0 */
        if (zr < -1.0e15) return false;
        double cr, ci; if (!pi_cot_c(zr, zi, &cr, &ci)) return false;
        double ur, ui; if (!digamma_upper(1.0 - zr, zi, &ur, &ui)) return false;
        ui = -ui;                               /* psi(conj w) = conj psi(w) */
        *outr = ur - cr; *outi = ui - ci;
        return isfinite(*outr) && isfinite(*outi);
    }
    /* psi(z) = psi(z + m) - sum_{j=0}^{m-1} 1/(z + j), Re(z + m) >= 10 */
    int m2 = zr < 10.0 ? (int)ceil(10.0 - zr) : 0;
    double ar, ai; dig_asym_c(zr + (double)m2, zi, &ar, &ai);
    double sr = 0.0, si = 0.0;
    for (int j = m2 - 1; j >= 0; j--) {
        double ir, ii; cx_recip(zr + (double)j, zi, &ir, &ii);
        sr += ir; si += ii;
    }
    *outr = ar - sr; *outi = ai - si;
    return isfinite(*outr) && isfinite(*outi);
}

static bool digamma_c(double zr, double zi, double* outr, double* outi) {
    if (!isfinite(zr) || !isfinite(zi)) return false;
    if (zi == 0.0) {
        double v; if (!sfg_digamma(zr, &v)) return false;
        *outr = v; *outi = 0.0; return true;
    }
    if (zi > 0.0) return digamma_upper(zr, zi, outr, outi);
    if (!digamma_upper(zr, -zi, outr, outi)) return false;
    *outi = -*outi;
    return true;
}

bool sfg_polygamma_c(int n, double zr, double zi, double* rr, double* ri) {
    if (!isfinite(zr) || !isfinite(zi)) return false;
    if (n == 0) return digamma_c(zr, zi, rr, ri);
    if (n < 0 || n > SFG_POLYGAMMA_MAX_N) return false;
    if (zi == 0.0) {
        double v; if (!sfg_polygamma(n, zr, &v)) return false;
        *rr = v; *ri = 0.0; return true;
    }
    if (zr < 0.0) return false;                 /* left half-plane: MPFR path */
    double xa = pg_threshold(n);
    int m = zr < xa ? (int)ceil(xa - zr) : 0;
    double wr = zr + (double)m;
    double sr, si;
    if (!hz_tail_c(n, wr, zi, &sr, &si)) return false;
    /* Rounding of Re(z) + m: zeta(n+1, w + e) = zeta(n+1, w)(1 - n e / w). */
    double ew = two_sum_err(zr, (double)m, wr);
    if (ew != 0.0) {
        double ir, ii; cx_recip(wr, zi, &ir, &ii);
        double fr = 1.0 - (double)n * ew * ir, fi = -(double)n * ew * ii;
        cx_mul(sr, si, fr, fi, &sr, &si);
    }
    double cr = 0.0, ci = 0.0;
    for (int j = m - 1; j >= 0; j--) {
        double tr = zr + (double)j;
        double vr, vi; ipow_recip_c(tr, zi, n + 1, &vr, &vi);
        double e = two_sum_err(zr, (double)j, tr);
        if (e != 0.0) {
            double ir, ii; cx_recip(tr, zi, &ir, &ii);
            double fr = 1.0 - (double)(n + 1) * e * ir, fi = -(double)(n + 1) * e * ii;
            cx_mul(vr, vi, fr, fi, &vr, &vi);
        }
        nsum_add(&sr, &cr, vr);
        nsum_add(&si, &ci, vi);
    }
    double f = sfg_factorial(n);
    if ((n & 1) == 0) f = -f;
    *rr = f * (sr + cr); *ri = f * (si + ci);
    return isfinite(*rr) && isfinite(*ri);
}

