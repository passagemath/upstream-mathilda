/*
 * stringcase.c - letter case and character-class predicates.
 *
 *   ToUpperCase[s] / ToLowerCase[s]   full Unicode case mapping (Listable):
 *                                     ToUpperCase["\:00df"] is "SS"
 *   Capitalize[s] / Decapitalize[s]   change the case of the first character
 *   LetterQ[s]                        every character is a letter (L*)
 *   DigitQ[s]                         every character is an ASCII digit 0-9
 *   UpperCaseQ[s] / LowerCaseQ[s]     every character is an upper- (Lu) /
 *                                     lowercase (Ll) letter
 *
 * The predicates are True for "" (vacuously), as in Mathematica. DigitQ is
 * ASCII-only in Mathematica (DigitQ["\:0662"] is False) even though the string
 * pattern DigitCharacter matches any Unicode decimal digit.
 *
 * Unicode data: src/strings/unicode_tables.inc, generated by
 * tools/gen_unicode_tables.py. ASCII is handled inline without the tables.
 */

#include "picostrings.h"
#include "strings_internal.h"
#include "utf8.h"
#include "sym_names.h"
#include "symtab.h"
#include "attr.h"

#include <stdlib.h>
#include <string.h>
#include <stdint.h>

typedef struct { uint32_t lo, hi; } U8Range;
typedef struct { uint32_t cp; uint8_t n; uint32_t to[3]; } U8CaseMap;

#include "unicode_tables.inc"

#define COUNT(a) (sizeof(a) / sizeof((a)[0]))

static int in_ranges(const U8Range* r, size_t n, uint32_t cp) {
    size_t lo = 0, hi = n;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (cp < r[mid].lo)      hi = mid;
        else if (cp > r[mid].hi) lo = mid + 1;
        else                     return 1;
    }
    return 0;
}

static const U8CaseMap* case_find(const U8CaseMap* t, size_t n, uint32_t cp) {
    size_t lo = 0, hi = n;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (cp < t[mid].cp)      hi = mid;
        else if (cp > t[mid].cp) lo = mid + 1;
        else                     return &t[mid];
    }
    return NULL;
}

/* ------------------------------------------------------------------ */
/* Case mapping                                                       */
/* ------------------------------------------------------------------ */

/*
 * Map the case of the characters of s[0, len) starting at character `from`
 * and covering `count` characters (SIZE_MAX: to the end); the rest is copied.
 * `upper` selects ToUpperCase vs ToLowerCase mapping. Returns a new String.
 */
static Expr* map_case(const char* s, size_t len, int upper, size_t from, size_t count) {
    /* A full mapping can grow one character to 3 code points of up to 4
     * bytes, so capacity is checked per character; the common case (output
     * the same size as the input) never reallocates. */
    if (len > (SIZE_MAX - 32) / 2) return NULL;
    size_t cap = len + 16, o = 0;
    char* out = malloc(cap);
    if (!out) return NULL;
    const U8CaseMap* tab = upper ? k_upper_map : k_lower_map;
    size_t ntab = upper ? COUNT(k_upper_map) : COUNT(k_lower_map);

    size_t ci = 0;
    for (size_t i = 0; i < len; ci++) {
        unsigned char c = (unsigned char)s[i];
        int active = ci >= from && (count == SIZE_MAX || ci - from < count);
        if (o + 12 + 1 > cap) {                 /* room for 3 x 4-byte chars */
            cap = cap * 2;
            char* nb = realloc(out, cap);
            if (!nb) { free(out); return NULL; }
            out = nb;
        }
        if (c < 0x80) {                         /* ASCII fast path */
            if (active) {
                if (upper && c >= 'a' && c <= 'z') c = (unsigned char)(c - 32);
                if (!upper && c >= 'A' && c <= 'Z') c = (unsigned char)(c + 32);
            }
            out[o++] = (char)c;
            i++;
            continue;
        }
        size_t start = i;
        uint32_t cp = u8_decode(s, len, &i);
        const U8CaseMap* m = active ? case_find(tab, ntab, cp) : NULL;
        if (!m) {                               /* unchanged: copy the bytes */
            memcpy(out + o, s + start, i - start);
            o += i - start;
        } else {
            for (int k = 0; k < m->n; k++) o += u8_encode(m->to[k], out + o);
        }
    }
    out[o] = '\0';
    return expr_new_string_adopt(out);
}

static int is_string_list(const Expr* e) {
    if (e->type != EXPR_FUNCTION || e->data.function.head->type != EXPR_SYMBOL ||
        e->data.function.head->data.symbol.name != SYM_List)
        return 0;
    for (size_t i = 0; i < e->data.function.arg_count; i++)
        if (e->data.function.args[i]->type != EXPR_STRING) return 0;
    return 1;
}

/* ToUpperCase / ToLowerCase: Listable, so only a String reaches here. Anything
 * else stays unevaluated (no message, as in Mathematica). */
static Expr* case_builtin(Expr* res, int upper) {
    if (res->type != EXPR_FUNCTION || res->data.function.arg_count != 1) return NULL;
    Expr* a = res->data.function.args[0];
    if (a->type != EXPR_STRING) return NULL;
    return map_case(a->data.string, strlen(a->data.string), upper, 0, SIZE_MAX);
}

Expr* builtin_touppercase(Expr* res) { return case_builtin(res, 1); }
Expr* builtin_tolowercase(Expr* res) { return case_builtin(res, 0); }

/* Capitalize / Decapitalize: the first character only; a string or a list of
 * strings (head::strse otherwise). */
static Expr* capitalize_builtin(Expr* res, const char* head, int upper) {
    if (res->type != EXPR_FUNCTION || res->data.function.arg_count != 1) return NULL;
    Expr* a = res->data.function.args[0];
    if (a->type == EXPR_STRING)
        return map_case(a->data.string, strlen(a->data.string), upper, 0, 1);
    if (!is_string_list(a))
        return strings_arg_message(head, "strse", "String or list of strings", 1, res);
    size_t n = a->data.function.arg_count;
    Expr* out = expr_new_function(expr_new_symbol(SYM_List), NULL, n);
    for (size_t i = 0; out && i < n; i++) {
        const char* s = a->data.function.args[i]->data.string;
        out->data.function.args[i] = map_case(s, strlen(s), upper, 0, 1);
        if (!out->data.function.args[i]) { expr_free(out); out = NULL; }
    }
    return out;
}

Expr* builtin_capitalize(Expr* res)   { return capitalize_builtin(res, "Capitalize", 1); }
Expr* builtin_decapitalize(Expr* res) { return capitalize_builtin(res, "Decapitalize", 0); }

/* ------------------------------------------------------------------ */
/* Character-class predicates                                         */
/* ------------------------------------------------------------------ */

typedef enum { CQ_LETTER, CQ_DIGIT, CQ_UPPER, CQ_LOWER } CharQ;

static int char_ok(CharQ q, uint32_t cp) {
    if (cp < 0x80) {
        switch (q) {
            case CQ_LETTER: return (cp | 32) >= 'a' && (cp | 32) <= 'z';
            case CQ_DIGIT:  return cp >= '0' && cp <= '9';
            case CQ_UPPER:  return cp >= 'A' && cp <= 'Z';
            case CQ_LOWER:  return cp >= 'a' && cp <= 'z';
        }
    }
    switch (q) {
        case CQ_LETTER: return in_ranges(k_letter_ranges, COUNT(k_letter_ranges), cp);
        case CQ_DIGIT:  return 0;
        case CQ_UPPER:  return in_ranges(k_upper_ranges, COUNT(k_upper_ranges), cp);
        case CQ_LOWER:  return in_ranges(k_lower_ranges, COUNT(k_lower_ranges), cp);
    }
    return 0;
}

static Expr* charq_builtin(Expr* res, const char* head, CharQ q) {
    if (res->type != EXPR_FUNCTION || res->data.function.arg_count != 1) return NULL;
    Expr* a = res->data.function.args[0];
    if (a->type != EXPR_STRING)
        return strings_arg_message(head, "string", "String", 1, res);
    const char* s = a->data.string;
    size_t len = strlen(s);
    for (size_t i = 0; i < len; ) {
        uint32_t cp = u8_decode(s, len, &i);
        if (!char_ok(q, cp)) return expr_new_symbol(SYM_False);
    }
    return expr_new_symbol(SYM_True);
}

Expr* builtin_letterq(Expr* res)    { return charq_builtin(res, "LetterQ", CQ_LETTER); }
Expr* builtin_digitq(Expr* res)     { return charq_builtin(res, "DigitQ", CQ_DIGIT); }
Expr* builtin_uppercaseq(Expr* res) { return charq_builtin(res, "UpperCaseQ", CQ_UPPER); }
Expr* builtin_lowercaseq(Expr* res) { return charq_builtin(res, "LowerCaseQ", CQ_LOWER); }
