/* Estrin's scheme rather than Horner: the same ~2*deg operations, but a
 * dependency chain of ~log2(deg) multiply-adds instead of deg, which is what
 * bounds a scalar call (no FMA in the default build, so each Horner step is a
 * dependent multiply then add: ~100 cycles of latency at degree 13). Written
 * out per degree -- GCC does not fully unroll a generic loop form, and an
 * Estrin tree left as a loop spills to the stack. estrinN(c, u) returns
 * sum_{j<N} c[N-1-j] u^j, i.e. the table row read from its low end. */
static inline double estrin6(const double* c, double u) {
    double u2 = u * u, u4 = u2 * u2;
    double t0_0 = c[5] + c[4] * u;
    double t0_1 = c[3] + c[2] * u;
    double t0_2 = c[1] + c[0] * u;
    double t1_0 = t0_0 + t0_1 * u2;
    double t2_0 = t1_0 + t0_2 * u4;
    return t2_0;
}
static inline double estrin7(const double* c, double u) {
    double u2 = u * u, u4 = u2 * u2;
    double t0_0 = c[6] + c[5] * u;
    double t0_1 = c[4] + c[3] * u;
    double t0_2 = c[2] + c[1] * u;
    double t1_0 = t0_0 + t0_1 * u2;
    double t1_1 = t0_2 + c[0] * u2;
    double t2_0 = t1_0 + t1_1 * u4;
    return t2_0;
}
