"""Generate src/special_functions/sf_machine_error_tables.h.

Every table is a piecewise polynomial fit made by fitlib (Chebyshev-node
interpolation in a centred variable, coefficients rounded to double, constant
term kept as a double-double). The script prints the measured approximation
error of each rounded piece; rerun it to reproduce the header bit for bit:

    benchmarks/.venv/bin/python -I tools/sf_fit/gen_tables.py > \
        src/special_functions/sf_machine_error_tables.h
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mpmath as mp
from fitlib import *

mp.mp.dps = 45
LOG = sys.stderr
OUT = []


def emit(s):
    OUT.append(s)


def family(name, g, lo, width, nseg, deg, rel=True, npts=40, what=""):
    pieces = []
    worst = 0.0
    for k in range(nseg):
        a = lo + k * width
        coef, mid, half, err = fit_piece(g, a, a + width, deg, rel, npts)
        pieces.append(coef)
        worst = max(worst, err)
        print("%s seg %d [%g,%g] deg %d err %.3f u" % (name, k, a, a + width, deg, err), file=LOG, flush=True)
    emit("/* %s: %s\n * %d segments of width %g from %g, degree %d in u = (x - mid)/%g;\n"
         " * max approximation error of the rounded table %.3f x 2^-53 (relative). */"
         % (name, what, nseg, width, lo, deg, width / 2, worst))
    emit(c_table(name, pieces))
    emit("")


def single(name, g, lo, hi, deg, rel=True, npts=60, what=""):
    coef, mid, half, err = fit_piece(g, lo, hi, deg, rel, npts)
    print("%s [%g,%g] deg %d err %.3f u" % (name, lo, hi, deg, err), file=LOG, flush=True)
    emit("/* %s: %s\n * one piece on [%.17g, %.17g], degree %d in u = (t - %.17g)/%.17g;\n"
         " * max approximation error %.3f x 2^-53. */" % (name, what, lo, hi, deg, mid, half, err))
    emit(c_table(name, [coef]))
    emit("#define %s_MID %.17g\n#define %s_IHALF %.17g\n" % (name, mid, name, 1 / mp.mpf(half)))


emit("/* GENERATED by tools/sf_fit/gen_tables.py -- do not edit by hand.\n"
     " * Piecewise polynomial tables for sf_machine_error.c. Each row holds the\n"
     " * coefficients of u^d .. u^1 and then the constant term as hi, lo; the\n"
     " * kernel evaluates  c0h + (c0l + u*(c1 + u*(... + u*cd))). */")
emit("#ifndef MATHILDA_SF_MACHINE_ERROR_TABLES_H\n#define MATHILDA_SF_MACHINE_ERROR_TABLES_H\n")

# erfcx(x) = e^{x^2} erfc(x) on [0.5, 6)
family("ERFCX_T", lambda x: mp.exp(x * x) * mp.erfc(x), 0.5, 0.5, 11, 13,
       what="erfcx(x) = e^{x^2} erfc(x), 0.5 <= x < 6")

# x erfcx(x) as a function of t = 1/x^2, 6 <= x <= 27 (one piece)
single("ERFCX2_T", lambda t: (lambda x: x * mp.exp(x * x) * mp.erfc(x))(1 / mp.sqrt(t)),
       mp.mpf(1) / 729, mp.mpf(1) / 36, 10, what="x erfcx(x) in t = 1/x^2, 6 <= x <= 27")

# e^{-x^2} erfi(x) = (2/sqrt(pi)) Dawson(x)
daw = lambda x: mp.exp(-x * x) * mp.erfi(x)
family("DAW1_T", daw, 0.5, 0.5, 7, 14, what="e^{-x^2} erfi(x), 0.5 <= x < 4")
family("DAW2_T", daw, 4.0, 0.5, 12, 11, what="e^{-x^2} erfi(x), 4 <= x < 10")


def fg(x):
    x = mp.mpf(x); ph = mp.pi * x * x / 2
    C = mp.fresnelc(x); S = mp.fresnels(x)
    return ((mp.mpf(1) / 2 - S) * mp.cos(ph) - (mp.mpf(1) / 2 - C) * mp.sin(ph),
            (mp.mpf(1) / 2 - C) * mp.cos(ph) + (mp.mpf(1) / 2 - S) * mp.sin(ph))


family("FRF1_T", lambda x: fg(x)[0], 1.0, 0.5, 6, 14, npts=30, what="Fresnel auxiliary f(x), 1 <= x < 4")
family("FRG1_T", lambda x: fg(x)[1], 1.0, 0.5, 6, 14, npts=30, what="Fresnel auxiliary g(x), 1 <= x < 4")
family("FRF2_T", lambda x: fg(x)[0], 4.0, 0.5, 8, 12, npts=30, what="Fresnel auxiliary f(x), 4 <= x < 8")
family("FRG2_T", lambda x: fg(x)[1], 4.0, 0.5, 8, 12, npts=30, what="Fresnel auxiliary g(x), 4 <= x < 8")


def invw(w):
    w = mp.mpf(w)
    if w == 0:
        return mp.sqrt(mp.pi) / 2
    p = mp.sqrt(-mp.expm1(-w))
    return erfinv_mp(p) / p


family("INVP_T", lambda p: erfinv_mp(p) / p if p != 0 else mp.sqrt(mp.pi) / 2,
       0.0, 0.0625, 14, 14, npts=30, what="erfinv(p)/p, 0 <= p < 0.875 (no logarithm needed)")

family("INVW_T", invw, 0.0, 1.0, 6, 11, npts=30,
       what="erfinv(p)/p as a function of w = -log(1 - p^2), 0 <= w < 6")


def invtail(v):
    s = 1 / mp.mpf(v); w = s * s
    e = mp.exp(-w); q = e / (1 + mp.sqrt(1 - e))
    return erfcinv_mp(q) / s


single("INVT_T", invtail, 1 / 27.4, 1 / 2.449, 11, npts=40,
       what="seed: erfcinv(q)/s, s = sqrt(-log(q(2-q))), v = 1/s (about 1e-7 relative; polished by Halley)")


# Faddeeva w(zeta) = e^{-zeta^2} erfc(-i zeta): Taylor coefficients about the
# centres of a 0.5 x 0.5 grid on [0,4] x [0,4] (Re, Im). The derivatives come
# from w' = -2 zeta w + 2i/sqrt(pi) at 60 digits (the forward recurrence loses
# at most ~25 digits over 20 steps here), so every stored coefficient is
# correctly rounded. Degree 20 keeps the truncation below 2^-56 |w| over each
# cell (|h| <= 0.354).
def w_taylor(c, K):
    with mp.workdps(70):
        c = mp.mpc(c)
        d = [mp.exp(-c * c) * mp.erfc(-1j * c)]
        d.append(-2 * c * d[0] + 2j / mp.sqrt(mp.pi))
        for k in range(1, K):
            d.append(-2 * c * d[k] - 2 * k * d[k - 1])
        out = []; f = mp.mpf(1)
        for k in range(K + 1):
            out.append(d[k] / f); f *= (k + 1)
        return out
WK = 20
rows = []
worst = 0.0
for i in range(8):          # Re index
    for j in range(8):      # Im index
        c = mp.mpc((i + 0.5) / 2, (j + 0.5) / 2)
        co = w_taylor(c, 40)
        r = mp.sqrt(2) / 4
        tail = mp.fsum(abs(co[k]) * r ** k for k in range(WK + 1, 41)) / abs(co[0])
        worst = max(worst, float(tail))
        row = []
        for k in range(WK + 1):
            row += [float(co[k].real), float(co[k].imag)]
        rows.append(row)
print("W_T truncation worst %.3g (relative)" % worst, file=LOG)
emit("/* W_T: Taylor coefficients of the Faddeeva function w about the centres\n"
     " * ((i + 1/2)/2) + i ((j + 1/2)/2), i, j = 0..7 (row 8 i + j), ascending\n"
     " * powers k = 0..%d stored as re, im; truncation <= %.2g |w| per cell. */" % (WK, worst))
emit("#define W_T_DEG %d" % WK)
out = ["static const double W_T[64][%d] = {" % (2 * (WK + 1))]
for r_ in rows:
    out.append("    { " + ", ".join("%.17g" % v for v in r_) + " },")
out.append("};")
emit("\n".join(out))
emit("")

# half-pi trigonometric kernels in t = s^2, |s| <= 1/2
single("SINHP_T", lambda t: mp.sin(mp.pi * mp.sqrt(t) / 2) / mp.sqrt(t) if t != 0 else mp.pi / 2,
       0, 0.25, 6, what="sin(pi s/2)/s in t = s^2")
single("COSHP_T", lambda t: mp.cos(mp.pi * mp.sqrt(t) / 2), 0, 0.25, 7, what="cos(pi s/2) in t = s^2")

# Cody-Waite pi/2 in three 33-bit pieces (k * piece exact for |k| < 2^20)
pio2 = mp.pi / 2
def chop(v, bits):
    e = int(mp.floor(mp.log(abs(v), 2)))
    q = mp.mpf(2) ** (e - bits + 1)
    return mp.floor(v / q) * q
p1 = chop(pio2, 33); p2 = chop(pio2 - p1, 33); p3 = pio2 - p1 - p2
emit("#define PIO2_1 %.17g\n#define PIO2_2 %.17g\n#define PIO2_3 %.17g\n#define TWO_OVER_PI %.17g\n"
     % (float(p1), float(p2), float(p3), float(2 / mp.pi)))
emit("#endif /* MATHILDA_SF_MACHINE_ERROR_TABLES_H */")
print("\n".join(OUT))
