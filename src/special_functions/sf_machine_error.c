/* =====================================================================
 * 1. double-double helpers
 * =====================================================================
 * Dekker's exact product (T. J. Dekker, "A floating-point technique for
 * extending the available precision", Numer. Math. 18 (1971)) and Knuth's
 * exact sum. These need round-to-nearest and NO contraction of a*b+c into an
 * fma -- which is what GCC does in ISO C mode (-std=c99 implies
 * -ffp-contract=off), and the build does not enable -march FMA anyway.
 *
 * Why they are needed: the error functions are exponentially sensitive to the
 * squares they exponentiate. erf(z) carries e^{-x^2}, e^{y^2} and the phase
 * 2xy; rounding x*x costs a relative error of |x|^2 * 2^-53 in e^{-x^2} --
 * nine ulps at x = 3 -- before any algorithm has run. Forming each square
 * exactly as hi + lo and folding lo in to first order removes that loss. */

static inline void dd_split(double a, double* hi, double* lo) {
    double c = 134217729.0 * a;           /* 2^27 + 1 */
    double h = c - (c - a);
    *hi = h;
    *lo = a - h;
}

/* p + e == a * b exactly. */
static inline void dd_mul(double a, double b, double* p, double* e) {
    double ah, al, bh, bl;
    double prod = a * b;
    dd_split(a, &ah, &al);
    dd_split(b, &bh, &bl);
    *p = prod;
    *e = ((ah * bh - prod) + ah * bl + al * bh) + al * bl;
}

/* s + e == a + b exactly. */
static inline void dd_add(double a, double b, double* s, double* e) {
    double t = a + b, bb = t - a;
    *s = t;
    *e = (a - (t - bb)) + (b - bb);
}

/* exp(h + l) for |l| << 1 (l is the low part of a double-double). */
static inline double exp_dd(double h, double l) {
    return exp(h) * (1.0 + l);
}

