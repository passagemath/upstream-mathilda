#!/usr/bin/env python3
"""Generate the complex node tables behind the mid-range K_mu kernels.

Writes src/special_functions/sf_machine_bessel_ktab.{c,h}.  Run with the
benchmark venv:

    benchmarks/.venv/bin/python -I tools/sf_accuracy/gen_bessel_ktab.py

For 5/4 <= |z| < 21 in the closed first quadrant -- where Temme's series has
cancelled away too many digits and Steed's continued fraction CF2 needs 30-160
iterations -- K_mu(z) and K_{mu+1}(z) are taken from the nearest node z0 of a
square grid and continued to z by the Taylor series of the modified Bessel
equation z^2 w'' + z w' - (z^2 + mu^2) w = 0 (DLMF 10.25.1) about z0; the
coefficient recurrence is in sf_machine_bessel.c (ktab_eval).  The nodes hold
the two values to double precision, from mpmath at 50 digits.

Two order pairs are tabulated: mu = 0 (K_0, K_1: the integer orders, by upward
recurrence) and mu = -1/3 (K_{1/3}, K_{2/3}: the Airy functions, and orders
+-1/3 mod 1).  Two grids each: spacing 1/4 on [0, 10]^2 (used for |z| < 10) and
1/2 on [0, 21]^2 (used for 10 <= |z| < 21).  Nodes outside the annulus a grid
serves are stored as zeros and never read.
"""
from __future__ import annotations

import os

import mpmath as mp

HERE = os.path.dirname(os.path.abspath(__file__))
WORKTREE = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(WORKTREE, "src", "special_functions", "sf_machine_bessel_ktab.c")
OUT_H = os.path.join(WORKTREE, "src", "special_functions", "sf_machine_bessel_ktab.h")
mp.mp.dps = 50

GRIDS = [  # name, spacing, count per axis, |node| range served (with margin)
    ("fine", 0.25, 41, 0.95, 10.3),
    ("coarse", 0.5, 43, 9.5, 21.5),
]
PAIRS = [("m0", mp.mpf(0)), ("m13", mp.mpf(-1) / 3)]


def main():
    with open(OUT, "w") as fh:
        fh.write("/* GENERATED by tools/sf_accuracy/gen_bessel_ktab.py -- do not edit.\n"
                 " * Node values K_mu(z0), K_{mu+1}(z0) as {re, im, re, im} per node, row-major\n"
                 " * in (x index, y index); see the generator for the method. */\n"
                 "#include \"sf_machine_bessel_ktab.h\"\n\n")
        for pname, mu in PAIRS:
            for gname, h, n, rlo, rhi in GRIDS:
                fh.write(f"const double sf_ktab_{gname}_{pname}[{n * n * 4}] = {{\n")
                for i in range(n):
                    for j in range(n):
                        z0 = mp.mpc(h * i, h * j)
                        if rlo <= abs(z0) <= rhi:
                            a = mp.besselk(mu, z0)
                            b = mp.besselk(mu + 1, z0)
                            vals = [a.real, a.imag, b.real, b.imag]
                        else:
                            vals = [0, 0, 0, 0]
                        fh.write("    " + ", ".join(f"{float(v):.17e}" for v in vals) + ",\n")
                fh.write("};\n\n")
                print(f"{pname} {gname} done", flush=True)
    with open(OUT_H, "w") as fh:
        fh.write("/* GENERATED by tools/sf_accuracy/gen_bessel_ktab.py -- do not edit. */\n"
                 "#ifndef MATHILDA_SF_MACHINE_BESSEL_KTAB_H\n"
                 "#define MATHILDA_SF_MACHINE_BESSEL_KTAB_H\n\n")
        for gname, h, n, rlo, rhi in GRIDS:
            G = gname.upper()
            fh.write(f"#define SF_KTAB_{G}_H {h!r}\n#define SF_KTAB_{G}_N {n}\n")
        for pname, _ in PAIRS:
            for gname, h, n, rlo, rhi in GRIDS:
                fh.write(f"extern const double sf_ktab_{gname}_{pname}[{n * n * 4}];\n")
        fh.write("\n#endif\n")
    print("wrote", OUT, OUT_H)


if __name__ == "__main__":
    main()
