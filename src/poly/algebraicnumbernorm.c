/* algebraicnumbernorm.c — AlgebraicNumberNorm[a].
 *
 * See algebraicnumbernorm.h.  The value — the field norm of an algebraic number,
 * optionally relative to a field Q(theta) given by Extension -> theta — is
 * computed exactly by flint_qqbar_algebraic_number_norm (both cases reduce to a
 * minimal-polynomial read; see flint_qqbar.c).  This file only separates the
 * positional argument from the Extension option (the first setting wins; an
 * unknown option is ::optx, a second positional argument ::nonopt, none
 * ::argx), maps the
 * tri/quad-state engine result to Integer/Rational / message / unevaluated, and
 * (being Listable) lets the evaluator thread over a list of algebraic numbers.
 */

#include "algebraicnumbernorm.h"

#include "flint_qqbar.h"
#include "symtab.h"
#include "attr.h"
#include "print.h"
#include "message.h"   /* mth_message: Quiet/Check funnel */
#include "sym_names.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* A two-argument Rule or RuleDelayed (a trailing option). */
static bool ann_is_rule(const Expr* e) {
    return e->type == EXPR_FUNCTION && e->data.function.arg_count == 2 &&
           e->data.function.head->type == EXPR_SYMBOL &&
           (e->data.function.head->data.symbol.name == SYM_Rule ||
            e->data.function.head->data.symbol.name == SYM_RuleDelayed);
}

/* The call's trailing options: Extension is the only one, and of repeated
 * settings the first wins. Sets *theta (borrowed; NULL for Automatic / None /
 * absent, i.e. the absolute norm over Q) and *npos, the positional count.
 * Returns false after AlgebraicNumberNorm::argx / ::nonopt / ::optx. */
static bool ann_options(Expr* res, const Expr** theta, size_t* npos) {
    size_t argc = res->data.function.arg_count;
    Expr** args = res->data.function.args;
    size_t first = argc;
    while (first > 0 && ann_is_rule(args[first - 1])) first--;
    *npos = first;
    *theta = NULL;
    if (first == 0) {
        mth_message("AlgebraicNumberNorm", "argx",
                    "AlgebraicNumberNorm called with %zu arguments; 1 argument is expected.",
                    argc);
        return false;
    }
    if (first > 1) {
        char* bad = expr_to_string(args[first - 1]);
        char* call = expr_to_string(res);
        mth_message("AlgebraicNumberNorm", "nonopt",
                    "Options expected (instead of %s) beyond position 1 in %s. "
                    "An option must be a rule or a list of rules.",
                    bad ? bad : "?", call ? call : "?");
        free(bad); free(call);
        return false;
    }
    bool seen = false;
    for (size_t i = first; i < argc; i++) {
        const Expr* key = args[i]->data.function.args[0];
        const Expr* val = args[i]->data.function.args[1];
        bool is_ext = (key->type == EXPR_SYMBOL && key->data.symbol.name == SYM_Extension) ||
                      (key->type == EXPR_STRING && strcmp(key->data.string, "Extension") == 0);
        if (!is_ext) {
            char* kname = key->type == EXPR_STRING ? NULL : expr_to_string((Expr*)key);
            char* call = expr_to_string(res);
            mth_message("AlgebraicNumberNorm", "optx", "Unknown option %s in %s.",
                        key->type == EXPR_STRING ? key->data.string : (kname ? kname : "?"),
                        call ? call : "?");
            free(kname); free(call);
            return false;
        }
        if (seen) continue;
        seen = true;
        bool trivial = val->type == EXPR_SYMBOL &&
                       (val->data.symbol.name == SYM_Automatic || val->data.symbol.name == SYM_None);
        *theta = trivial ? NULL : val;
    }
    return true;
}

Expr* builtin_algebraicnumbernorm(Expr* res) {
    if (res->type != EXPR_FUNCTION) return NULL;

    const Expr* theta;
    size_t npos;
    if (!ann_options(res, &theta, &npos)) return NULL;

    const Expr* a = res->data.function.args[0];
    Expr* out = NULL;
    int r = flint_qqbar_algebraic_number_norm(a, theta, &out);
    if (r == 1) return out;                  /* success: the norm */
    if (r < 0) return NULL;                   /* undecided (FLINT compiled out) */

    if (r == 2) {                             /* a is not an element of Q(theta) */
        char* s = expr_to_string((Expr*)a);
        char* t = expr_to_string((Expr*)theta);
        mth_message("ToNumberField", "nnfel",
                    "%s does not belong to the algebraic number field generated by %s.",
                    s ? s : "?", t ? t : "?");
        free(s); free(t);
        return NULL;
    }

    /* r == 0: not a constant algebraic number — report and stay unevaluated. */
    char* s = expr_to_string((Expr*)a);
    mth_message("AlgebraicNumberNorm", "nalg", "%s is not an explicit algebraic number.", s ? s : "?");
    free(s);
    return NULL;
}

void algebraicnumbernorm_init(void) {
    symtab_add_builtin("AlgebraicNumberNorm", builtin_algebraicnumbernorm);
    /* Listable: AlgebraicNumberNorm[{a1, ..}] threads element-wise, giving one
     * norm per algebraic number; a trailing Extension option is repeated. */
    symtab_get_def("AlgebraicNumberNorm")->attributes |=
        ATTR_LISTABLE | ATTR_PROTECTED;
}
