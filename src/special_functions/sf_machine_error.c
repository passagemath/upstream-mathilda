#define SALZER_EXP_M14 0.77880078307140488   /* e^{-1/4} */
#define SALZER_EXP_M12 0.60653065971263342   /* e^{-1/2} */
#define SALZER_YS      0.5                   /* recurrence / scaled switch   */
#define SALZER_YMAX    26.0                  /* beyond: e^{Y^2} overflows    */

/* Everything the series needs about X + iY, computed accurately by the
 * caller. X >= 0, Y >= 0. */
typedef struct {
    double X, Y;      /* the argument (main parts)                           */
    double Yl;        /* low part of Y (double-double), 0 for an exact Y     */
    double erfX;      /* erf(X)                                              */
    double emx2;      /* e^{-X^2}                                            */
    double eyh, eyl;  /* Y^2 - X^2 as a double-double; read when Y > SALZER_YS */
    double sn, cn;    /* sin(XY), cos(XY)                                    */
    double snx;       /* sin(XY)/X, with the limit Y at X = 0                */
} ErfArgs;

/* cosh(Y + Yl), sinh(Y + Yl) for 0 <= Y, accurate also for small Y. */
static void salzer_cosh_sinh(double Y, double Yl, double* ch, double* sh) {
    double em = expm1(Y);                 /* e^Y - 1, exact-ish near 0 */
    double E = em + 1.0;
    double s = 0.5 * (em + em / E);       /* sinh Y = (em + em/(em+1))/2 */
    double c = 0.5 * (E + 1.0 / E);
    *sh = s + c * Yl;
    *ch = c + s * Yl;
}

/* erf(X + iY) - erf(X) = cr + i ci, for X, Y >= 0, Y <= SALZER_YMAX. */
static void salzer_core(const ErfArgs* a, double* cr, double* ci) {
    const double X = a->X, Y = a->Y;
    const double fx2 = 4.0 * X * X;
    const double sn = a->sn, cn = a->cn;
    const double s = 2.0 * sn * cn;                /* sin 2XY */
    const double c = (cn - sn) * (cn + sn);        /* cos 2XY */
    const double omc = 2.0 * sn * sn;              /* 1 - cos 2XY */
    const int N = (int)(2.0 * Y + 13.0);

    if (Y <= SALZER_YS) {
        /* Direct recurrence on (cosh nY, sinh nY). */
        double ch1, sh1;
        salzer_cosh_sinh(Y, a->Yl, &ch1, &sh1);
        double ch = ch1, sh = sh1;
        double S0 = 0.0, SD = 0.0, SS = 0.0;
        for (int n = 1; n <= N; n++) {
            double en = SALZER_G[n] / ((double)n * n + fx2);
            /* cosh - 1 without cancellation while nY is small */
            double chm1 = (ch < 1.5) ? sh * sh / (ch + 1.0) : ch - 1.0;
            S0 += en;
            SD += en * chm1;
            SS += en * (double)n * sh;
            double nch = ch * ch1 + sh * sh1;
            sh = sh * ch1 + ch * sh1;
            ch = nch;
        }
        /* Re: (1-c)/(2X) + 4X S0 - 4X c SC, with SC = S0 + SD
         *     = sin^2/X + 4X (1-c) S0 - 4X c SD.
         * Im: s/(2X) + 2c SS + 4X s SC. */
        double re = sn * a->snx + 4.0 * X * omc * S0 - 4.0 * X * c * SD + 2.0 * s * SS;
        double im = cn * a->snx + 2.0 * c * SS + 4.0 * X * s * (S0 + SD);
        *cr = a->emx2 * INV_PI * re;
        *ci = a->emx2 * INV_PI * im;
        return;
    }

    /* Scaled regime: e^{-n^2/4} cosh(nY) = e^{Y^2} (P_n + Q_n)/2,
     *                e^{-n^2/4} sinh(nY) = e^{Y^2} (P_n - Q_n)/2,
     * P_n = e^{-(n/2 - Y)^2},  Q_n = e^{-(n/2 + Y)^2} = P_n e^{-2nY}.
     * Everything is carried relative to the peak term P_{n0}, n0 = round(2Y),
     * and the single factor e^{Y^2 - X^2} P_{n0} = e^{Y^2 - X^2 - d0^2} is
     * applied once at the end from a double-double exponent: one rounding,
     * where e^{Y^2}, e^{-X^2} and P_{n0} as three exps were three. */
    int n0 = (int)(2.0 * Y + 0.5);
    if (n0 < 1) n0 = 1;
    if (n0 > N) n0 = N;
    double d0 = (0.5 * n0 - Y) - a->Yl;            /* exact head (Sterbenz) */
    double dsh, dsl, sch, scl;
    dd_mul(d0, d0, &dsh, &dsl);
    dd_add(a->eyh, -dsh, &sch, &scl);
    double scale = exp_dd(sch, scl + (a->eyl - dsl)); /* e^{Y^2-X^2} P_{n0} */
    double Ed = exp(-d0);                           /* e^{-d0}              */
    /* e^{-2Y} = e^{-n0} e^{2 d0} (Y = n0/2 - d0): a table entry and Ed, not a
     * third exp. Q_n = P_n e^{-2nY} is below 2^-55 of P_n once 2Y > 38, so the
     * mirror terms are dropped there. */
    double eY2 = SALZER_EXPN[n0] / (Ed * Ed);
    double Mn0 = 0.0;                               /* e^{-2 n0 Y}          */
    if (Y < 19.0) {
        double b2 = eY2;
        Mn0 = 1.0;
        for (int k = n0; k; k >>= 1) { if (k & 1) Mn0 *= b2; b2 *= b2; }
    }

    /* The sums run outward from the peak, so every term added is smaller
     * than the running sum and Fast2Sum (Dekker) captures each addition's
     * rounding exactly; the compensations are folded in at the end. Without
     * them the ~2Y+13 roundings cost up to ~2 ulps of the final value. */
    double SC = 0.0, SSs = 0.0, S0 = 0.0, eSC = 0.0, eSS = 0.0;
#define SALZER_ACC(SUM, ERR, V) do { double v_ = (V), t_ = SUM + v_;  \
        ERR += v_ - (t_ - SUM); SUM = t_; } while (0)
    {   /* forward: n = n0 .. N */
        double P = 1.0, r = Ed * SALZER_EXP_M14;    /* P_{n+1}/P_n = e^{-d_n - 1/4} */
        double M = Mn0;
        for (int n = n0; n <= N; n++) {
            double q = 1.0 / ((double)n * n + fx2);
            double Q = P * M;
            if (n <= 13) S0 += SALZER_G[n] * q;
            SALZER_ACC(SC, eSC, (P + Q) * q);
            SALZER_ACC(SSs, eSS, (double)n * (P - Q) * q);
            P *= r;
            r *= SALZER_EXP_M12;
            M *= eY2;
        }
    }
    {   /* backward: n = n0-1 .. 1 */
        double P = 1.0, r = SALZER_EXP_M14 / Ed;    /* P_{n-1}/P_n = e^{d_n - 1/4} */
        double M = Mn0, eY2i = (Mn0 != 0.0) ? 1.0 / eY2 : 0.0;
        for (int n = n0 - 1; n >= 1; n--) {
            P *= r;
            r *= SALZER_EXP_M12;
            M *= eY2i;
            double q = 1.0 / ((double)n * n + fx2);
            double Q = P * M;
            if (n <= 13) S0 += SALZER_G[n] * q;
            SALZER_ACC(SC, eSC, (P + Q) * q);
            SALZER_ACC(SSs, eSS, (double)n * (P - Q) * q);
        }
    }
#undef SALZER_ACC
    SC += eSC; SSs += eSS;
    SC *= 0.5; SSs *= 0.5;
    /* With SC_true = e^{Y^2} P_{n0}^{-1}... i.e. SC_true e^{-X^2} = scale SC:
     *   Re = sin^2/X + 4X S0 - 4X c SC_true + 2 s SS_true
     *   Im = s/(2X) + 2c SS_true + 4X s SC_true                             */
    *cr = INV_PI * (a->emx2 * (sn * a->snx + 4.0 * X * S0)
                    + scale * (2.0 * s * SSs - 4.0 * X * c * SC));
    *ci = INV_PI * (a->emx2 * cn * a->snx
                    + scale * (2.0 * c * SSs + 4.0 * X * s * SC));
}

/* ---------------------------------------------------------------------
 * The Faddeeva function w(zeta) = e^{-zeta^2} erfc(-i zeta) on the box
 * 0 <= Re zeta < 4, 0 <= Im zeta < 4, by Taylor expansion about the centre of
 * a 0.5 x 0.5 cell (W_T, generated at 60 digits from the derivative
 * recurrence w' = -2 zeta w + 2i/sqrt(pi); degree 20, truncation < 2^-56 |w|).
 * This is the inner-region strategy of the Faddeeva literature (Poppe &
 * Wijers 1990, Zaghloul & Ali 2011 tabulate or sum near the axis) in its
 * simplest form: w is bounded and smooth in the upper half-plane, so a
 * polynomial per cell is uniformly accurate, and evaluating it costs ~200
 * flops with no transcendental call -- against the ~2Y+13 terms, each with a
 * division, of Salzer's series. The complex polynomial is evaluated by
 * Estrin's scheme (five levels) rather than Horner (twenty dependent steps).
 * Callers reach w only for the arguments their identities need:
 *     erf(z)  = 1 - e^{-z^2} w(iz),   erfc(z) = e^{-z^2} w(iz)   (Re z >= 0)
 * and w(-conj zeta) = conj w(zeta) folds Re zeta < 0 onto the table. */
#define CMA(XR, XI, YR, YI, HR, HI, OR, OI) do { double yr_ = (YR), yi_ = (YI); \
        OR = (XR) + (yr_ * (HR) - yi_ * (HI)); OI = (XI) + (yr_ * (HI) + yi_ * (HR)); } while (0)

/* w(a + ib) for 0 <= a < 4, 0 <= b < 4 (the caller guarantees the box). */
static void w_box(double a, double b, double* wr, double* wi) {
    int i = (int)(a * 2.0), j = (int)(b * 2.0);
    const double* c = W_T[8 * i + j];
    double hr = a - (0.5 * i + 0.25), hi = b - (0.5 * j + 0.25);
    double h2r = (hr - hi) * (hr + hi), h2i = 2.0 * hr * hi;
    double h4r = (h2r - h2i) * (h2r + h2i), h4i = 2.0 * h2r * h2i;
    double h8r = (h4r - h4i) * (h4r + h4i), h8i = 2.0 * h4r * h4i;
    double h16r = (h8r - h8i) * (h8r + h8i), h16i = 2.0 * h8r * h8i;
    double p[10][2], q[5][2], r[3][2], s0r, s0i;
    for (int k = 0; k < 10; k++)
        CMA(c[4 * k], c[4 * k + 1], c[4 * k + 2], c[4 * k + 3], hr, hi, p[k][0], p[k][1]);
    for (int k = 0; k < 5; k++)
        CMA(p[2 * k][0], p[2 * k][1], p[2 * k + 1][0], p[2 * k + 1][1], h2r, h2i, q[k][0], q[k][1]);
    CMA(q[0][0], q[0][1], q[1][0], q[1][1], h4r, h4i, r[0][0], r[0][1]);
    CMA(q[2][0], q[2][1], q[3][0], q[3][1], h4r, h4i, r[1][0], r[1][1]);
    CMA(q[4][0], q[4][1], c[40], c[41], h4r, h4i, r[2][0], r[2][1]);
    CMA(r[0][0], r[0][1], r[1][0], r[1][1], h8r, h8i, s0r, s0i);
    CMA(s0r, s0i, r[2][0], r[2][1], h16r, h16i, *wr, *wi);
}

/* Maclaurin coefficients of erf(z) (2/sqrt(pi))^-1 z^-1:  (-1)^k/(k!(2k+1)). */
static const double ERF_MAC[22] = {
    1, -0.33333333333333331, 0.10000000000000001, -0.023809523809523808,
    0.0046296296296296294, -0.00075757575757575758, 0.00010683760683760684,
    -1.3227513227513228e-05, 1.4589169000933706e-06, -1.4503852223150468e-07,
    1.3122532963802806e-08, -1.0892221037148573e-09, 8.3507027951472397e-11,
    -5.9477940136376354e-12, 3.9554295164585257e-13, -2.4668270102644571e-14,
    1.4483264643598138e-15, -8.0327350124157733e-17, 4.2214072888070882e-18,
    -2.1078551914421359e-19, 1.0025164934907719e-20, -4.5518467589281999e-22
};
#define ERF_MAC_R2 0.64      /* |z| <= 0.8: inside, 1 - e^{-z^2} w would cancel */
#define ERFC_MAC_R2 0.25     /* erfc = 1 - erf only while erf <= 0.52           */

/* sum_{k<19} a[k] w^k for real a and complex w, by Estrin's scheme. */
static inline void cpoly19(const double* a, double wr, double wi, double* pr, double* pi) {
    double w2r = (wr - wi) * (wr + wi), w2i = 2.0 * wr * wi;
    double w4r = (w2r - w2i) * (w2r + w2i), w4i = 2.0 * w2r * w2i;
    double w8r = (w4r - w4i) * (w4r + w4i), w8i = 2.0 * w4r * w4i;
    double w16r = (w8r - w8i) * (w8r + w8i), w16i = 2.0 * w8r * w8i;
    double t0_0r = a[0] + a[1] * wr, t0_0i = a[1] * wi;
    double t0_1r = a[2] + a[3] * wr, t0_1i = a[3] * wi;
    double t0_2r = a[4] + a[5] * wr, t0_2i = a[5] * wi;
    double t0_3r = a[6] + a[7] * wr, t0_3i = a[7] * wi;
    double t0_4r = a[8] + a[9] * wr, t0_4i = a[9] * wi;
    double t0_5r = a[10] + a[11] * wr, t0_5i = a[11] * wi;
    double t0_6r = a[12] + a[13] * wr, t0_6i = a[13] * wi;
    double t0_7r = a[14] + a[15] * wr, t0_7i = a[15] * wi;
    double t0_8r = a[16] + a[17] * wr, t0_8i = a[17] * wi;
    double t1_0r = t0_0r + (t0_1r * w2r - t0_1i * w2i), t1_0i = t0_0i + (t0_1r * w2i + t0_1i * w2r);
    double t1_1r = t0_2r + (t0_3r * w2r - t0_3i * w2i), t1_1i = t0_2i + (t0_3r * w2i + t0_3i * w2r);
    double t1_2r = t0_4r + (t0_5r * w2r - t0_5i * w2i), t1_2i = t0_4i + (t0_5r * w2i + t0_5i * w2r);
    double t1_3r = t0_6r + (t0_7r * w2r - t0_7i * w2i), t1_3i = t0_6i + (t0_7r * w2i + t0_7i * w2r);
    double t1_4r = t0_8r + a[18] * w2r, t1_4i = t0_8i + a[18] * w2i;
    double t2_0r = t1_0r + (t1_1r * w4r - t1_1i * w4i), t2_0i = t1_0i + (t1_1r * w4i + t1_1i * w4r);
    double t2_1r = t1_2r + (t1_3r * w4r - t1_3i * w4i), t2_1i = t1_2i + (t1_3r * w4i + t1_3i * w4r);
    double t3_0r = t2_0r + (t2_1r * w8r - t2_1i * w8i), t3_0i = t2_0i + (t2_1r * w8i + t2_1i * w8r);
    double t4_0r = t3_0r + (t1_4r * w16r - t1_4i * w16i), t4_0i = t3_0i + (t1_4r * w16i + t1_4i * w16r);
    *pr = t4_0r; *pi = t4_0i;
}

/* erf(X + iY) by its Maclaurin series (|z|^2 <= ERF_MAC_R2): a polynomial in
 * z^2 with real coefficients (19 terms), evaluated by Estrin's scheme. */
static void erf_maclaurin(double X, double Y, double* re, double* im) {
    double wr = (X - Y) * (X + Y), wi = 2.0 * X * Y;   /* z^2 */
    double pr, pi;
    cpoly19(ERF_MAC, wr, wi, &pr, &pi);
    *re = TWO_OVER_SQRTPI * (pr * X - pi * Y);
    *im = TWO_OVER_SQRTPI * (pr * Y + pi * X);
}

/* The Salzer inputs for an EXACT argument X + iY (X, Y >= 0 doubles). */
static void erf_args_exact(double X, double Y, ErfArgs* a) {
    double x2, x2l, p, pl;
    dd_mul(X, X, &x2, &x2l);
    dd_mul(X, Y, &p, &pl);
    a->X = X; a->Y = Y; a->Yl = 0.0;
    a->emx2 = exp_dd(-x2, -x2l);
    a->erfX = erf_real_fast(X, a->emx2);
    sincos_rad(p, pl, &a->sn, &a->cn);
    a->snx = (X == 0.0) ? Y : a->sn / X;
    a->eyh = a->eyl = 0.0;
    if (Y > SALZER_YS) {
        double y2, y2l, eh, el;
        dd_mul(Y, Y, &y2, &y2l);
        dd_add(y2, -x2, &eh, &el);
        a->eyh = eh;
        a->eyl = el + (y2l - x2l);
    }
}

/* erf(X + iY) and erfc(X + iY) for 0 <= X, Y < 4 from the w table:
 *   e^{-z^2} w(iz),  w(iz) = w(-Y + iX) = conj w(Y + iX),
 * given mag = e^{Y^2 - X^2} and (c2, s2) = (cos 2XY, sin 2XY), each formed
 * by the caller from an exact (double-double) exponent and phase. */
static void erfc_from_w(double X, double Y, double mag, double c2, double s2,
                        double* re, double* im) {
    double wr, wi;
    w_box(Y, X, &wr, &wi);
    /* (c2 - i s2)(wr - i wi) */
    *re = mag * (c2 * wr - s2 * wi);
    *im = -mag * (s2 * wr + c2 * wi);
}

/* The exact pieces for an exact argument X + iY. */
static void w_pieces_exact(double X, double Y, double* mag, double* c2, double* s2) {
    double x2, x2l, y2, y2l, eh, el, p, pl;
    dd_mul(X, X, &x2, &x2l);
    dd_mul(Y, Y, &y2, &y2l);
    dd_add(y2, -x2, &eh, &el);
    *mag = exp_dd(eh, el + (y2l - x2l));
    dd_mul(X, Y, &p, &pl);
    sincos_rad(2.0 * p, 2.0 * pl, s2, c2);
}

/* erf(X + iY) for X, Y >= 0; false when Y is beyond the series' range.
 *   |z| <= 1/2         Maclaurin (1 - e^{-z^2} w would cancel)
 *   X, Y < 4           1 - e^{-z^2} w(iz), w from the table
 *   otherwise          Salzer's series                                   */
static bool erf_quadrant(double X, double Y, double* re, double* im) {
    if (X * X + Y * Y <= ERF_MAC_R2) { erf_maclaurin(X, Y, re, im); return true; }
    if (X < 4.0 && Y < 4.0) {
        double mag, c2, s2, er, ei;
        w_pieces_exact(X, Y, &mag, &c2, &s2);
        erfc_from_w(X, Y, mag, c2, s2, &er, &ei);
        *re = 1.0 - er;
        *im = -ei;
        return true;
    }
    if (Y > SALZER_YMAX) return false;
    ErfArgs a;
    double cr, ci;
    erf_args_exact(X, Y, &a);
    salzer_core(&a, &cr, &ci);
    *re = a.erfX + cr;
    *im = ci;
    return true;
}

bool sf_erf_c(double x, double y, double* re, double* im) {
    double fr, fi;
    if (!isfinite(x) || !isfinite(y)) return false;
    if (!erf_quadrant(fabs(x), fabs(y), &fr, &fi)) return false;
    /* erf is odd and real on the real axis:
     * erf(x + iy) = sign(x) Re F + i sign(y) Im F, F = erf(|x| + i|y|). */
    *re = signbit(x) ? -fr : fr;
    *im = signbit(y) ? -fi : fi;
    return isfinite(*re) && isfinite(*im);
}

bool sf_erfc_c(double x, double y, double* re, double* im) {
    double X = fabs(x), Y = fabs(y), fr, fi;
    if (!isfinite(x) || !isfinite(y)) return false;
    if (x >= 0.0 && X * X + Y * Y > ERFC_MAC_R2) {
        if (X < 4.0 && Y < 4.0) {                       /* e^{-z^2} w(iz) */
            double mag, c2, s2;
            w_pieces_exact(X, Y, &mag, &c2, &s2);
            erfc_from_w(X, Y, mag, c2, s2, &fr, &fi);
            *re = fr;
            *im = signbit(y) ? -fi : fi;
            return isfinite(*re) && isfinite(*im);
        }
        /* erfc(X + iY) = erfc(X) - (erf(X + iY) - erf(X)): no cancellation
         * against 1 when erfc is small (X large). */
        if (Y > SALZER_YMAX || X > 26.0) return false;   /* erfc(X) underflows */
        ErfArgs a;
        double cr, ci;
        erf_args_exact(X, Y, &a);
        salzer_core(&a, &cr, &ci);
        fr = erfc_real_fast(X, a.emx2) - cr;
        fi = -ci;
        *re = fr;
        *im = signbit(y) ? -fi : fi;
        return isfinite(*re) && isfinite(*im);
    }
    /* x < 0 (erfc = 1 - erf ~ 1..2, no cancellation) or |z| small. */
    if (!erf_quadrant(X, Y, &fr, &fi)) return false;
    *re = 1.0 - (signbit(x) ? -fr : fr);
    *im = -(signbit(y) ? -fi : fi);
    return isfinite(*re) && isfinite(*im);
}

bool sf_erfi_c(double x, double y, double* re, double* im) {
    /* erfi(z) = -i erf(iz), iz = -y + ix. */
    double u, v;
    if (!sf_erf_c(-y, x, &u, &v)) return false;
    *re = v;
    *im = -u;
    return true;
}

/* =====================================================================
 * 3. Complex Fresnel integrals
 * =====================================================================
 * DLMF 7.3.22 in Mathematica's convention:
 *   C(z) + i S(z) = ((1+i)/2) erf(eta),   eta  = (sqrt(pi)/2)(1 - i) z,
 *   C(z) - i S(z) = ((1-i)/2) erf(eta'),  eta' = (sqrt(pi)/2)(1 + i) z,
 * so C = [(1+i) E1 + (1-i) E2]/4 and S = [(1+i) E1 - (1-i) E2]/(4i).
 *
 * eta is NOT rounded and handed to the complex erf. Rounding it costs a
 * relative error of ~|eta erf'(eta)/erf(eta)| ~ pi |z|^2 eps -- 25 ulps at
 * |z| = 2.8, which is what an erf-of-rounded-argument Fresnel delivers. Instead
 * every quantity the series exponentiates is formed from the EXACT x, y:
 *   eta = X + iY,  X = k (x + y),  Y = k (y - x),  k = sqrt(pi)/2,
 *   X^2        = (pi/4)(x + y)^2               (double-double)
 *   X Y        = (pi/4)(y^2 - x^2)             (double-double, reduced mod 2pi)
 *   Y^2 - X^2  = -pi x y                       (double-double)
 * and for eta' the roles are X' = -k(y - x), Y' = k(x + y), X'Y' = -XY,
 * Y'^2 - X'^2 = +pi x y.
 * Near the origin the combination cancels (S ~ pi z^3/6 out of two O(z)
 * terms), so |z| <= 1 uses the Maclaurin series instead. */

static const double FRESNEL_MAC_C[16] = {
    1, -0.24674011002723398, 0.028185500877894225, -0.0016048831356425355,
    5.4074133814083916e-05, -1.2000972558600288e-06, 1.8843499115272686e-08,
    -2.2022769254454663e-10, 1.9896857924180219e-12, -1.4309189731715198e-14,
    8.3847297051185541e-17, -4.0799814492338779e-19, 1.6748476126215183e-21,
    -5.877896118036892e-24, 1.7837783103437512e-26, -4.7272263847426812e-29
};
static const double FRESNEL_MAC_S[16] = {
    0.52359877559829893, -0.092280585358035183, 0.0072447842041970037,
    -0.00031211694235457922, 8.4442728835452544e-06, -1.5647144500922109e-07,
    2.1082121933214546e-09, -2.1574306805843444e-11, 1.7334102088874846e-13,
    -1.1223244787983955e-15, 5.9800532392104046e-18, -2.6678713628413992e-20,
    1.011069642466722e-22, -3.295271477907068e-25, 9.3343826890209932e-28, -2.3192836677213777e-30
};
#define FRESNEL_MAC_R2 1.69    /* |z| <= 1.3: past it the two-erf combination cancels less than the series */
#define FRESNEL_MAC_K  14      /* (pi/2)^30 1.69^30/(30! 61) < 2^-60 */

#define SQRTPI2_H 0.88622692545275805      /* sqrt(pi)/2, double-double */
#define SQRTPI2_L (-3.8332932499128993e-17)
#define PI4_H     0.78539816339744828      /* pi/4 */
#define PI4_L     3.061616997868383e-17
#define PI_H      3.1415926535897931       /* pi */
#define PI_L      1.2246467991473532e-16

/* sin and cos of (pi/4) t for a double-double t = th + tl >= 0, reduced
 * exactly: t = 2m + r with |r| <= 1, so the angle is m pi/2 + (pi/4) r. */
static void sincos_pi4_dd(double th, double tl, double* s, double* c) {
    double m = (th < 2251799813685248.0) ? rint_small(0.5 * th) : 0.5 * th;
    double r = (th - 2.0 * m) + tl;          /* th - 2m is exact (Sterbenz) */
    double sa, ca;
    sincos_halfpi(0.5 * r, &sa, &ca);        /* (pi/4) r = (pi/2)(r/2) */
    quarter_turn(mod4(m), sa, ca, s, c);
}

/* erf(eta) for eta = X + iY given as k*(a) + i k*(b), with the pieces of the
 * exact argument precomputed (see the block comment). Writes erf(eta). */
static bool fresnel_erf(double ah, double al,   /* X = k a  (a double-double) */
                        double bh, double bl,   /* Y = k b                     */
                        double x2h, double x2l, /* X^2 (double-double)         */
                        double ph, double pl,   /* Y^2 - X^2                   */
                        double th, double tl,   /* |X Y| = (pi/4) t, t >= 0    */
                        double* re, double* im) {
    /* X = k a, Y = k b as double-doubles. */
    double Xh, Xl, Yh, Yl;
    dd_mul(SQRTPI2_H, ah, &Xh, &Xl);
    Xl += SQRTPI2_H * al + SQRTPI2_L * ah;
    dd_mul(SQRTPI2_H, bh, &Yh, &Yl);
    Yl += SQRTPI2_H * bl + SQRTPI2_L * bh;
    double sgx = (Xh < 0.0 || (Xh == 0.0 && Xl < 0.0)) ? -1.0 : 1.0;
    double sgy = (Yh < 0.0 || (Yh == 0.0 && Yl < 0.0)) ? -1.0 : 1.0;
    double X = fabs(Xh), XL = sgx * Xl;
    double Y = fabs(Yh), YL = sgy * Yl;

    if (X < 4.0 && Y < 4.0) {
        /* 1 - e^{-eta^2} w(i eta): e^{-eta^2} = e^{Y^2-X^2} e^{-2iXY} from the
         * exact exponent and the exactly reduced phase 2|XY| = (pi/2) t. The
         * table argument (Y, X) is the rounded eta, to which w is benign. */
        double c2, s2, er, ei;
        sincos_halfpi_dd(th, tl, &s2, &c2);
        erfc_from_w(X, Y, exp_dd(ph, pl), c2, s2, &er, &ei);
        *re = sgx * (1.0 - er);
        *im = -sgy * ei;
        return true;
    }
    if (Y > SALZER_YMAX) return false;

    ErfArgs A;
    double sxy, cxy;
    sincos_pi4_dd(th, tl, &sxy, &cxy);
    A.X = X; A.Y = Y; A.Yl = YL;
    A.emx2 = exp_dd(-x2h, -x2l);
    A.erfX = erf_real_fast(X, A.emx2) + TWO_OVER_SQRTPI * A.emx2 * XL;
    A.sn = sxy; A.cn = cxy;
    A.snx = (X == 0.0) ? Y : sxy / X;
    A.eyh = ph; A.eyl = pl;
    double cr, ci;
    salzer_core(&A, &cr, &ci);
    *re = sgx * (A.erfX + cr);
    *im = sgy * ci;
    return true;
}

/* Both Fresnel integrals of z = x + iy at once. */
static bool fresnel_cs_c(double x, double y,
                         double* cre, double* cim, double* sre, double* sim) {
    if (!isfinite(x) || !isfinite(y)) return false;
    if (x * x + y * y <= FRESNEL_MAC_R2) {
        /* Maclaurin: C = z sum c_k w^k, S = z^3 sum s_k w^k, w = z^4. */
        double z2r = (x - y) * (x + y), z2i = 2.0 * x * y;
        double wr = (z2r - z2i) * (z2r + z2i), wi = 2.0 * z2r * z2i;
        double pr = FRESNEL_MAC_C[FRESNEL_MAC_K], pi = 0.0;
        double qr = FRESNEL_MAC_S[FRESNEL_MAC_K], qi = 0.0;
        for (int k = FRESNEL_MAC_K - 1; k >= 0; k--) {
            double t = pr * wr - pi * wi + FRESNEL_MAC_C[k];
            pi = pr * wi + pi * wr; pr = t;
            t = qr * wr - qi * wi + FRESNEL_MAC_S[k];
            qi = qr * wi + qi * wr; qr = t;
        }
        *cre = pr * x - pi * y;
        *cim = pr * y + pi * x;
        double z3r = z2r * x - z2i * y, z3i = z2r * y + z2i * x;
        *sre = qr * z3r - qi * z3i;
        *sim = qr * z3i + qi * z3r;
        return true;
    }
    /* u = x + y, v = y - x, exactly. */
    double uh, ul, vh, vl;
    dd_add(x, y, &uh, &ul);
    dd_add(y, -x, &vh, &vl);
    /* X^2 = (pi/4) u^2,  X'^2 = (pi/4) v^2. */
    double u2h, u2l, v2h, v2l, X2h, X2l, X2ph, X2pl;
    dd_mul(uh, uh, &u2h, &u2l); u2l += 2.0 * uh * ul;
    dd_mul(vh, vh, &v2h, &v2l); v2l += 2.0 * vh * vl;
    dd_mul(PI4_H, u2h, &X2h, &X2l);  X2l  += PI4_H * u2l + PI4_L * u2h;
    dd_mul(PI4_H, v2h, &X2ph, &X2pl); X2pl += PI4_H * v2l + PI4_L * v2h;
    /* pi x y */
    double xyh, xyl, pxyh, pxyl;
    dd_mul(x, y, &xyh, &xyl);
    dd_mul(PI_H, xyh, &pxyh, &pxyl); pxyl += PI_H * xyl + PI_L * xyh;
    /* |y^2 - x^2| for the phase */
    double x2h, x2l, y2h, y2l, th, tl;
    dd_mul(x, x, &x2h, &x2l);
    dd_mul(y, y, &y2h, &y2l);
    dd_add(y2h, -x2h, &th, &tl); tl += y2l - x2l;
    if (th < 0.0) { th = -th; tl = -tl; }

    double a, b, c, d;     /* E1 = a + ib = erf(eta), E2 = c + id = erf(eta') */
    if (!fresnel_erf(uh, ul, vh, vl, X2h, X2l, -pxyh, -pxyl, th, tl, &a, &b))
        return false;
    if (!fresnel_erf(-vh, -vl, uh, ul, X2ph, X2pl, pxyh, pxyl, th, tl, &c, &d))
        return false;
    *cre = 0.25 * ((a - b) + (c + d));
    *cim = 0.25 * ((a + b) + (d - c));
    *sre = 0.25 * ((a + b) + (c - d));
    *sim = 0.25 * ((b - a) + (c + d));
    return isfinite(*cre) && isfinite(*cim) && isfinite(*sre) && isfinite(*sim);
}

bool sf_fresnel_c_c(double x, double y, double* re, double* im) {
    double sr, si;
    return fresnel_cs_c(x, y, re, im, &sr, &si);
}
bool sf_fresnel_s_c(double x, double y, double* re, double* im) {
    double cr, ci;
    return fresnel_cs_c(x, y, &cr, &ci, re, im);
}

/* =====================================================================
 * 4. Real erfi
 * =====================================================================
 * erfi(x) = (2/sqrt(pi)) e^{x^2} D(x) with D Dawson's integral. The smooth,
 * bounded factor g(x) = e^{-x^2} erfi(x) is tabulated (0.5 <= x < 10) and the
 * growth e^{x^2} is applied from the double-double square, so the result
 * carries the table's sub-ulp error plus ~1 ulp of exp -- where summing the
 * all-positive Maclaurin series (the old kernel) cost ~80 ns at |x| ~ 3 and
 * accumulated 30 ulps by |x| ~ 5.
 *   |x| < 0.5   (2/sqrt(pi)) x sum t^k/(k!(2k+1)), t = x^2 (positive terms)
 *   |x| < 10    e^{x^2} g(x) from DAW1_T / DAW2_T
 *   |x| >= 10   e^{x^2}/(sqrt(pi) x) sum (2k-1)!!/(2x^2)^k  (asymptotic;
 *               14 terms reach 2^-60 at x = 10, and the remainder there is
 *               O(e^{-x^2}))
 *   e^{x^2} overflowing while erfi itself is representable (x^2 in
 *   (709, 713.6)) is handled by scaling with e^{-64}; beyond, decline. */
static const double ERFI_ASY[15] = {
    1, 1, 3, 15, 105, 945, 10395, 135135, 2027025, 34459425, 654729075,
    13749310575.0, 316234143225.0, 7905853580625.0, 213458046676875.0
};
#define SQRTPI_INV 0.56418958354775628695   /* 1/sqrt(pi) */
#define EXP_P64    6.2351490808116168829e+27 /* e^{64}     */

bool sf_erfi_r(double x, double* out) {
    double X = fabs(x), v;
    if (!(X < 26.72)) {                      /* NaN, Inf, or overflow */
        return false;
    }
    if (X < 0.5) {
        double t = X * X, p = fabs(ERF_MAC_R[12]);
        for (int k = 11; k >= 0; k--) p = p * t + fabs(ERF_MAC_R[k]);
        v = TWO_OVER_SQRTPI * X * p;
    } else {
        double g;
        if (X < 4.0) {
            int i = (int)((X - 0.5) * 2.0);
            g = tpoly(DAW1_T[i], 14, (X - (0.75 + 0.5 * i)) * 4.0);
        } else if (X < 10.0) {
            int i = (int)((X - 4.0) * 2.0);
            g = tpoly(DAW2_T[i], 11, (X - (4.25 + 0.5 * i)) * 4.0);
        } else {
            double w = 1.0 / (2.0 * X * X), p = ERFI_ASY[14];
            for (int k = 13; k >= 0; k--) p = p * w + ERFI_ASY[k];
            g = SQRTPI_INV / X * p;
        }
        double x2, x2l;
        dd_mul(X, X, &x2, &x2l);
        if (x2 < 709.0) v = exp_dd(x2, x2l) * g;
        else            v = (exp_dd(x2 - 64.0, x2l) * g) * EXP_P64;
    }
    *out = (x < 0.0) ? -v : v;
    return isfinite(v);
}

/* =====================================================================
 * 5. Real Fresnel integrals
 * =====================================================================
 * DLMF 7.5.3-4 with the auxiliary functions f, g (DLMF 7.2.10-11):
 *   C(x) = 1/2 + f(x) sin(pi x^2/2) - g(x) cos(pi x^2/2)
 *   S(x) = 1/2 - f(x) cos(pi x^2/2) - g(x) sin(pi x^2/2),
 * f, g smooth and monotone (f ~ 1/(pi x), g ~ 1/(pi^2 x^3)), which is the
 * Cephes `fresnl` structure with the rational fits replaced by 0.5-wide
 * polynomial tables.
 *   |x| <= 1   Maclaurin: C = x sum c_k x^{4k}, S = x^3 sum s_k x^{4k}
 *   1 < |x| < 8   f, g from FRF*_T / FRG*_T
 *   8 <= |x|      the asymptotic series of f and g (DLMF 7.12.2-3), nine
 *                 terms reach 2^-60 at x = 8
 *   |x| > 2^54    C = S = 1/2 (the oscillating term is below half an ulp).
 * The phase pi x^2/2 is reduced EXACTLY: x^2 = hi + lo (Dekker), hi - k for
 * the nearest integer k is exact, so (pi/2)(x^2 mod 4) costs no rounding at
 * all; libm's sin(pi*x*x/2) would carry an absolute phase error of ~x^2 ulps
 * (the old kernel's dominant error beyond x ~ 3). */
static const double FR_ASY_F[9] = {
    1, -3, 105, -10395, 2027025, -654729075, 316234143225.0,
    -213458046676875.0, 1.91898783962510625e17
};
static const double FR_ASY_G[9] = {
    1, -15, 945, -135135, 34459425, -13749310575.0, 7905853580625.0,
    -6190283353629375.0, 6.332659870762850625e18
};
#define INV_PI2 0.10132118364233777144   /* 1/pi^2 */

static void fresnel_cs_r(double x, double* c, double* s) {
    double X = fabs(x), C, S;
    if (X <= 1.0) {
        double t = X * X, w = t * t;
        double pc = FRESNEL_MAC_C[11], ps = FRESNEL_MAC_S[11];
        for (int k = 10; k >= 0; k--) {
            pc = pc * w + FRESNEL_MAC_C[k];
            ps = ps * w + FRESNEL_MAC_S[k];
        }
        double t2, t2l, x3, x3l;               /* x^3 to within an ulp/4 */
        dd_mul(X, X, &t2, &t2l);
        dd_mul(X, t2, &x3, &x3l);
        x3l += X * t2l;
        C = X * pc;
        S = x3 * ps + x3l * ps;
    } else if (X > 18014398509481984.0) {    /* 2^54 */
        C = S = 0.5;
    } else {
        double f, g;
        if (X < 4.0) {
            int i = (int)((X - 1.0) * 2.0);
            double u = (X - (1.25 + 0.5 * i)) * 4.0;
            f = tpoly(FRF1_T[i], 14, u);
            g = tpoly(FRG1_T[i], 14, u);
        } else if (X < 8.0) {
            int i = (int)((X - 4.0) * 2.0);
            double u = (X - (4.25 + 0.5 * i)) * 4.0;
            f = tpoly(FRF2_T[i], 12, u);
            g = tpoly(FRG2_T[i], 12, u);
        } else {
            double px2 = M_PI * X * X, v = 1.0 / (px2 * px2);
            double pf = FR_ASY_F[8], pg = FR_ASY_G[8];
            for (int k = 7; k >= 0; k--) { pf = pf * v + FR_ASY_F[k]; pg = pg * v + FR_ASY_G[k]; }
            f = INV_PI / X * pf;
            g = INV_PI2 / (X * X * X) * pg;
        }
        /* phase (pi/2) x^2, reduced exactly */
        double t, tl, sp, cp;
        dd_mul(X, X, &t, &tl);
        sincos_halfpi_dd(t, tl, &sp, &cp);
        C = 0.5 + (f * sp - g * cp);
        S = 0.5 - (f * cp + g * sp);
    }
    *c = (x < 0.0) ? -C : C;
    *s = (x < 0.0) ? -S : S;
}

bool sf_fresnel_c_r(double x, double* out) {
    double c, s;
    if (!isfinite(x)) return false;
    fresnel_cs_r(x, &c, &s);
    *out = c;
    return true;
}

bool sf_fresnel_s_r(double x, double* out) {
    double c, s;
    if (!isfinite(x)) return false;
    fresnel_cs_r(x, &c, &s);
    *out = s;
    return true;
}

/* =====================================================================
 * 6. Sinc
 * ===================================================================== */

/* Real: sin(x)/x -- libm's sin is accurate relative to its own value even next
 * to its zeros, so the quotient is within ~1.5 ulp everywhere. Identical to
 * sf_machine_sinc, which the NDArray and Compile surfaces already used. */
bool sf_sinc_r(double x, double* out) {
    *out = (x == 0.0) ? 1.0 : sin(x) / x;
    return isfinite(*out);
}

/* Taylor coefficients of sin(z)/z in z^2: (-1)^k/(2k+1)!. */
static const double SINC_MAC[11] = {
    1, -0.16666666666666666, 0.0083333333333333332, -0.00019841269841269841,
    2.7557319223985893e-06, -2.505210838544172e-08, 1.6059043836821613e-10,
    -7.6471637318198164e-13, 2.8114572543455206e-15, -8.2206352466243295e-18,
    1.9572941063391263e-20
};

/* Complex: sin z / z with sin(x+iy) = sin x cosh y + i cos x sinh y.
 * |z| <= 1 uses the even Maclaurin series (no division, no 0/0); elsewhere
 * the quotient is formed against |z|^2, which cannot overflow or underflow
 * for the |z| > 1, |y| <= 710 this branch sees. */
bool sf_sinc_c(double x, double y, double* re, double* im) {
    if (!isfinite(x) || !isfinite(y)) return false;
    if (x * x + y * y <= 1.0) {
        double wr = (x - y) * (x + y), wi = 2.0 * x * y;
        double pr = SINC_MAC[10], pi = 0.0;
        for (int k = 9; k >= 0; k--) {
            double t = pr * wr - pi * wi + SINC_MAC[k];
            pi = pr * wi + pi * wr; pr = t;
        }
        *re = pr; *im = pi;
        return true;
    }
    if (fabs(y) > 709.0 || fabs(x) > 1e150) return false;
    double em = expm1(fabs(y)), E = em + 1.0;
    double sh = 0.5 * (em + em / E), ch = 0.5 * (E + 1.0 / E);
    if (y < 0.0) sh = -sh;
    double sx, cx;
    sincos_rad(fabs(x), 0.0, &sx, &cx);
    if (x < 0.0) sx = -sx;
    double a = sx * ch, b = cx * sh;                  /* sin z = a + ib */
    double d = x * x + y * y;
    *re = (a * x + b * y) / d;
    *im = (b * x - a * y) / d;
    return isfinite(*re) && isfinite(*im);
}

/* =====================================================================
 * 7. InverseErf, InverseErfc
 * =====================================================================
 * Both are erfinv(p) for an erf-value p in [0, 1) together with its exact
 * complement q = 1 - p. Following M. Giles, "Approximating the erfinv
 * function" (GPU Computing Gems, 2011), the variable is
 *     w = -log(1 - p^2) = -log(q (2 - q)),
 * in which erfinv(p)/p is analytic in the strip |Im w| < pi (the only
 * singularity of erfinv, p = +-1, sits at w = +infinity), so it is
 * approximated far more economically than in p. Giles uses one polynomial on
 * [0, 6.25) of degree ~22; here six unit-width pieces of degree 11, selected
 * by table index (no data-dependent branch), sit far below an ulp:
 *     0 <= w < 6     erfinv = p * P_i(w)            (p up to 0.99876)
 *     w >= 6         the tail: z0 = s * T(1/s), s = sqrt(w), good to ~1e-7,
 *                    then ONE Halley step on erfc(z) = q (cubic: 1e-7 ->
 *                    1e-21), written with the relative residual so neither
 *                    e^{-z^2} nor e^{z^2} is formed.
 * The old kernel was Winitzki's closed form plus up to four Newton steps,
 * each costing an erf and an exp.
 * Domain: the kernels decline p outside (-1, 1) and q outside (0, 2) (the
 * endpoints are the exact +-Infinity the builtins answer themselves) and a
 * subnormal q, whose own few bits the Halley residual cannot resolve. */
static double erfinv_core(double p, double q) {
    if (p < 0.875) {
        int i = (int)(p * 16.0);
        return p * tpoly(INVP_T[i], 14, (p - (i + 0.5) * 0.0625) * 32.0);
    }
    double w = -log(q * (2.0 - q));
    if (w < 6.0) {
        int i = (int)w;
        return p * tpoly(INVW_T[i], 11, (w - (i + 0.5)) * 2.0);
    }
    double sw = sqrt(w), v = 1.0 / sw;
    double z = sw * tpoly(INVT_T[0], 11, (v - INVT_T_MID) * INVT_T_IHALF);
    /* Halley on f(z) = erfc(z) - q, f' = -(2/sqrt(pi)) e^{-z^2},
     * f''/f' = -2z:  z <- z - t/(1 + z t),  t = f/f'
     *   = -((erfc(z) - q)/erfc(z)) (sqrt(pi)/2) erfcx(z),
     * with erfcx(z) = e^{z^2} erfc(z) from the table (z < 6) or its
     * asymptotic series (12 terms: 1e-11 relative at z = 6, ample for a
     * correction that is itself ~1e-7 of z). */
    double ez = erfc(z);
    double rho = (ez - q) / ez;
    double ecx;
    if (z < 6.0) ecx = erfcx_tab(z);
    else {
        double h = -1.0 / (2.0 * z * z), p2 = ERFI_ASY[12];
        for (int k = 11; k >= 0; k--) p2 = p2 * h + ERFI_ASY[k];
        ecx = SQRTPI_INV / z * p2;
    }
    double t = -rho * SQRTPI_OVER_2 * ecx;
    return z - t / (1.0 + z * t);
}

bool sf_inverse_erf_r(double x, double* out) {
    double p = fabs(x);
    if (!(p < 1.0)) return false;            /* +-1 (Infinity), |x| > 1, NaN */
    if (p == 0.0) { *out = x; return true; }
    double v = erfinv_core(p, 1.0 - p);
    *out = (x < 0.0) ? -v : v;
    return isfinite(v);
}

bool sf_inverse_erfc_r(double y, double* out) {
    if (!(y > 2.2250738585072014e-308 && y < 2.0)) return false;
    /* erfcinv(y) = erfinv(1 - y): p = |1 - y| (exact for y >= 1/2; below, it
     * is only used while p < 0.875, where its half-ulp rounding costs < 1 ulp)
     * and the exact complement q = min(y, 2 - y). Written without a branch on
     * which half y is in: random arguments made that one mispredict ~half the
     * time. */
    double d = 1.0 - y;
    double p = fabs(d);
    double q = (y < 1.0) ? y : 2.0 - y;
    double v = (p == 0.0) ? 0.0 : erfinv_core(p, q);
    *out = (d < 0.0) ? -v : v;
    return isfinite(v);
}
