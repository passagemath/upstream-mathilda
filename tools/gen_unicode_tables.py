#!/usr/bin/env python3
"""Generate src/strings/unicode_tables.inc -- the Unicode data behind
ToUpperCase / ToLowerCase / Capitalize / Decapitalize and LetterQ /
UpperCaseQ / LowerCaseQ (src/strings/stringcase.c).

Usage: tools/gen_unicode_tables.py > src/strings/unicode_tables.inc

Source: Python's unicodedata and str.upper()/str.lower() (full case mappings,
so U+00DF uppercases to "SS", as in Mathematica). Emits:
  - k_letter_ranges / k_upper_ranges / k_lower_ranges: sorted, disjoint
    [lo, hi] code-point ranges of the categories L*, Lu, Ll;
  - k_upper_map / k_lower_map: sorted (code point -> 1..3 code points) for every
    character whose mapping differs from itself.
"""
import sys, unicodedata

def ranges(pred):
    out, lo = [], None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and lo is None: lo = cp
        if not ok and lo is not None:
            out.append((lo, cp - 1)); lo = None
    if lo is not None: out.append((lo, 0x10FFFF))
    return out

def cat(cp):
    return unicodedata.category(chr(cp))

def casemap(fn):
    out = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF: continue
        m = fn(chr(cp))
        if m != chr(cp):
            assert 1 <= len(m) <= 3, (cp, m)
            out.append((cp, [ord(c) for c in m]))
    return out

def emit_ranges(name, rs):
    print(f"static const U8Range {name}[] = {{")
    for lo, hi in rs: print(f"    {{0x{lo:04X}u, 0x{hi:04X}u}},")
    print("};")

def emit_map(name, m):
    print(f"static const U8CaseMap {name}[] = {{")
    for cp, seq in m:
        seq3 = seq + [0] * (3 - len(seq))
        print(f"    {{0x{cp:04X}u, {len(seq)}, {{0x{seq3[0]:04X}u, 0x{seq3[1]:04X}u, 0x{seq3[2]:04X}u}}}},")
    print("};")

print(f"/* Generated by tools/gen_unicode_tables.py from Unicode "
      f"{unicodedata.unidata_version} -- do not edit. */")
emit_ranges("k_letter_ranges", ranges(lambda cp: cat(cp).startswith("L")))
emit_ranges("k_upper_ranges", ranges(lambda cp: cat(cp) == "Lu"))
emit_ranges("k_lower_ranges", ranges(lambda cp: cat(cp) == "Ll"))
emit_map("k_upper_map", casemap(str.upper))
emit_map("k_lower_map", casemap(str.lower))
