/* Digamma, real                                                      */
/* ------------------------------------------------------------------ */

/* psi(1 + t) for t in [0, 1], t supplied EXACTLY by the caller. */
static inline double dig_core(double t) {
    return poly4_rr(SFG_DIG12, 24, t - 0.5) * ((t - SFG_X0M1_HI) - SFG_X0M1_LO);
}

/* psi(x) for x >= 10: log x - 1/(2x) - sum_{k=1}^{9} B_2k / (2k x^2k).
 * The first omitted term is below 3e-18 at x = 10 (DLMF 5.11.2). */
static inline double dig_asym(double x) {
    double inv = 1.0 / x, z = inv * inv;
    double p = SFG_DIGAMMA_ASY[8];
    for (int k = 7; k >= 0; k--) p = p * z + SFG_DIGAMMA_ASY[k];
    return log(x) - 0.5 * inv - p * z;
}

bool sfg_digamma(double x, double* out) {
    if (!isfinite(x)) return false;
    double v;
    if (x <= 0.0) {
        double fl = floor(x);
        if (x == fl || x < -1.0e15) return false;          /* pole / no digits left */
        /* psi(x) = psi(1-x) - pi cot(pi x); reduce the cotangent's argument to
         * r = x - nearest integer, which is exact. */
        double r = x - fl;
        if (r > 0.5) r -= 1.0;
        double a = M_PI * r;
        double up;
        if (!sfg_digamma(1.0 - x, &up)) return false;
        v = up - M_PI * cos(a) / sin(a);
    } else if (x < 1.0) {
        v = dig_core(x) - 1.0 / x;                          /* psi(x) = psi(x+1) - 1/x */
    } else if (x <= 2.0) {
        v = dig_core(x - 1.0);
    } else if (x < 10.0) {
        /* psi(x) = psi(x - m) + sum_{j=1}^{m} 1/(x - j), x - m in [1, 2).
         * Each x - j is exact; the sum is added smallest term first. */
        int m = (int)x - 1;
        double s = 0.0;
        for (int j = 1; j <= m; j++) s += 1.0 / (x - (double)j);
        v = s + dig_core(x - (double)(m + 1));
    } else {
        v = dig_asym(x);
    }
    *out = v;
    return isfinite(v);
}

