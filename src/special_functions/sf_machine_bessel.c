#define AIRY_C1 0.3550280538878172          /* Ai(0)   */
#define AIRY_C2 0.2588194037928068          /* -Ai'(0) */
#define SQRT3   1.7320508075688772
#define AIRY_MAC_R 1.0

/* Maclaurin coefficients in w = z^3 (DLMF 9.4.1-9.4.4):
 *   f = sum A_k w^k, g = z sum B_k w^k, f' = z^2 sum AP_k w^k, g' = sum BP_k w^k. */
static const double AIRY_A[10] = {
    1.00000000000000000e+00, 1.66666666666666657e-01, 5.55555555555555577e-03,
    7.71604938271604923e-05, 5.84549195660306779e-07, 2.78356759838241336e-09,
    9.09662613850461810e-12, 2.16586336631062337e-14, 3.92366551867866536e-17,
    5.58926712062487935e-20 };
static const double AIRY_B[10] = {
    1.00000000000000000e+00, 8.33333333333333287e-02, 1.98412698412698402e-03,
    2.20458553791887140e-05, 1.41319585764030204e-07, 5.88831607350125831e-10,
    1.72172984605299955e-12, 3.72668797846969601e-15, 6.21114663078282709e-18,
    8.21580242167040596e-21 };
static const double AIRY_AP[10] = {
    5.00000000000000000e-01, 3.33333333333333329e-02, 6.94444444444444471e-04,
    7.01459034792368135e-06, 4.17535139757362004e-08, 1.63739270493083139e-10,
    4.54831306925230945e-13, 9.41679724482879786e-16, 1.50910212256871745e-18,
    1.92733348987064808e-21 };
static const double AIRY_BP[10] = {
    1.00000000000000000e+00, 3.33333333333333315e-01, 1.38888888888888881e-02,
    2.20458553791887113e-04, 1.83715461493239276e-06, 9.42130571760201330e-09,
    3.27128670750069899e-11, 8.19871355263333139e-14, 1.55278665769570667e-16,
    2.30042467806771379e-19 };

static cx chorner(const double* c, int deg, cx w) {
    cx s = cxm(c[deg], 0.0);
    for (int k = deg - 1; k >= 0; k--) s = cadd(cmul(s, w), cxm(c[k], 0.0));
    return s;
}

/* Error-free transforms (Knuth's TwoSum; TwoProd by fma). */
static inline void two_sum(double a, double b, double* s, double* e) {
    double x = a + b, bb = x - a;
    *e = (a - (x - bb)) + (b - bb);
    *s = x;
}
static inline void two_prod(double a, double b, double* p, double* e) {
    double x = a * b;
    *e = fma(a, b, -x);
    *p = x;
}

/* a*b - c*d as hi + lo. */
static void dd_diff_prod(double a, double b, double c, double d, double* hi, double* lo) {
    double p, pe, q, qe, s, se;
    two_prod(a, b, &p, &pe);
    two_prod(c, d, &q, &qe);
    two_sum(p, -q, &s, &se);
    *hi = s; *lo = se + (pe - qe);
}

/* sqrt(z) = s + slo and zeta = (2/3) z^{3/2} = zh + zl, principal branches. */
static void airy_zeta_dd_c(cx z, cx* s, cx* zh, cx* zl) {
    cx sq = csqrtz(z);
    /* residual z - sq^2, componentwise in double-double */
    double a = sq.re, b = sq.im;
    double rh, rl;
    dd_diff_prod(a, a, b, b, &rh, &rl);           /* re(sq^2) = a^2 - b^2 */
    double r1, r1e;
    two_sum(z.re, -rh, &r1, &r1e);
    double rre = r1 + (r1e - rl);
    double p, pe;
    two_prod(2.0 * a, b, &p, &pe);                 /* im(sq^2) = 2ab */
    double i1, i1e;
    two_sum(z.im, -p, &i1, &i1e);
    double rim = i1 + (i1e - pe);
    cx slo = cdiv(cxm(rre, rim), cscal(sq, 2.0));
    /* P = z * (sq + slo) in double-double */
    double prh, prl, pih, pil;
    dd_diff_prod(z.re, a, z.im, b, &prh, &prl);
    dd_diff_prod(z.re, b, -z.im, a, &pih, &pil);   /* zr b + zi a */
    cx zs = cmul(z, slo);
    prl += zs.re; pil += zs.im;
    double h1 = prh * TWO_THIRDS_HI, h2 = pih * TWO_THIRDS_HI;
    *zh = cxm(h1, h2);
    *zl = cxm(fma(prh, TWO_THIRDS_HI, -h1) + (prh * TWO_THIRDS_LO + prl * TWO_THIRDS_HI),
              fma(pih, TWO_THIRDS_HI, -h2) + (pih * TWO_THIRDS_LO + pil * TWO_THIRDS_HI));
    *s = sq;
}

/* All four Airy values at complex z. `need_b`: Bi/Bi' wanted (else only
 * Ai/Ai' are guaranteed). */
static bool airy_complex(cx z, bool need_b, cx* ai, cx* aip, cx* bi, cx* bip) {
    double rho = hypot(z.re, z.im);
    if (!isfinite(rho)) return false;
    if (rho <= AIRY_MAC_R) {
        cx w = cmul(cmul(z, z), z);
        cx f  = chorner(AIRY_A, 9, w);
        cx g  = cmul(z, chorner(AIRY_B, 9, w));
        cx fp = cmul(cmul(z, z), chorner(AIRY_AP, 9, w));
        cx gp = chorner(AIRY_BP, 9, w);
        *ai  = csub(cscal(f, AIRY_C1), cscal(g, AIRY_C2));
        *aip = csub(cscal(fp, AIRY_C1), cscal(gp, AIRY_C2));
        *bi  = cscal(cadd(cscal(f, AIRY_C1), cscal(g, AIRY_C2)), SQRT3);
        *bip = cscal(cadd(cscal(fp, AIRY_C1), cscal(gp, AIRY_C2)), SQRT3);
        return true;
    }
    cx sq, zh, zl;
    airy_zeta_dd_c(z, &sq, &zh, &zl);
    bool cont = zh.re < 0.0;
    cx w = cont ? cneg(zh) : zh;
    int need = NEED_1 | ((need_b || cont) ? NEED_I : 0);
    cx Iv = cxm(0, 0), Kv = Iv, I1 = Iv, K1 = Iv;     /* orders -1/3 and 2/3 */
    if (!ik_rhp(-1.0 / 3.0, w, need, &Iv, &Kv, &I1, &K1)) return false;
    if (cont) {
        double sg = (z.im < 0.0) ? -1.0 : 1.0;
        cx ipi = cxm(0.0, sg * M_PI);
        cx Iv2 = cmul(cispi(sg * (-1.0 / 3.0)), Iv);
        cx I12 = cmul(cispi(sg * (2.0 / 3.0)), I1);
        cx Kv2 = csub(cmul(cispi(-sg * (-1.0 / 3.0)), Kv), cmul(ipi, Iv));
        cx K12 = csub(cmul(cispi(-sg * (2.0 / 3.0)), K1), cmul(ipi, I1));
        Iv = Iv2; I1 = I12; Kv = Kv2; K1 = K12;
    }
    const double INV_PI = 0.3183098861837907, INV_PI_SQRT3 = 0.18377629847393068;
    const double SQRT3_PI = 0.5513288954217921, INV_SQRT3 = 0.5773502691896257;
    cx sq3 = cscal(sq, INV_SQRT3);                     /* sqrt(z/3) */
    cx A  = cscal(cmul(sq3, Kv), INV_PI);
    cx Ap = cscal(cmul(z, K1), -INV_PI_SQRT3);
    /* first-order correction for the low part of zeta */
    cx Ac  = cadd(A,  cmul(cdiv(Ap, sq), zl));
    cx Apc = cadd(Ap, cmul(cmul(sq, A), zl));
    *ai = Ac; *aip = Apc;
    if (need_b) {
        cx B  = cmul(sq3, csub(cscal(Iv, 2.0), cscal(Kv, SQRT3_PI)));
        cx Bp = cscal(cmul(z, cadd(cscal(I1, 2.0), cscal(K1, SQRT3_PI))), INV_SQRT3);
        *bi  = cadd(B,  cmul(cdiv(Bp, sq), zl));
        *bip = cadd(Bp, cmul(cmul(sq, B), zl));
    } else {
        *bi = *bip = cxm(0.0, 0.0);
    }
    return true;
}

static bool airy_c_one(int which, double zr, double zi, double* rr, double* ri) {
    if (!isfinite(zr) || !isfinite(zi)) return false;
    cx a, ap, b, bp;
    if (!airy_complex(cxm(zr, zi), which >= AIRY_BI, &a, &ap, &b, &bp)) return false;
    cx v = (which == AIRY_AI) ? a : (which == AIRY_AIP) ? ap : (which == AIRY_BI) ? b : bp;
    if (zi == 0.0) v.im = 0.0;                    /* real on the real axis */
    if (!cx_ok(v)) return false;
    *rr = v.re; *ri = v.im;
    return true;
}

bool sf_airy_ai_c(double zr, double zi, double* rr, double* ri)  { return airy_c_one(AIRY_AI, zr, zi, rr, ri); }
bool sf_airy_aip_c(double zr, double zi, double* rr, double* ri) { return airy_c_one(AIRY_AIP, zr, zi, rr, ri); }
bool sf_airy_bi_c(double zr, double zi, double* rr, double* ri)  { return airy_c_one(AIRY_BI, zr, zi, rr, ri); }
bool sf_airy_bip_c(double zr, double zi, double* rr, double* ri) { return airy_c_one(AIRY_BIP, zr, zi, rr, ri); }

