/* Shared small tools                                                 */
/* ------------------------------------------------------------------ */

/* The rounding error of s = fl(a + b): a + b = s + e exactly (Knuth TwoSum). */
static inline double two_sum_err(double a, double b, double s) {
    double bv = s - a, av = s - bv;
    return (a - av) + (b - bv);
}

/* Neumaier's compensated accumulation: *s + *c carries the running sum. */
static inline void nsum_add(double* s, double* c, double t) {
    double u = *s + t;
    if (fabs(*s) >= fabs(t)) *c += (*s - u) + t;
    else                     *c += (t - u) + *s;
    *s = u;
}

/* t^-(k) for t > 0, choosing the order of power and reciprocal so that the
 * single division is not amplified k-fold. */
static inline double ipow_recip_d(double t, int k) {
    return (t >= 1.0 && t <= 64.0) ? 1.0 / ipow_d(t, k) : ipow_d(1.0 / t, k);
}
static inline void ipow_recip_c(double tr, double ti, int k, double* rr, double* ri) {
    double m = fabs(tr) > fabs(ti) ? fabs(tr) : fabs(ti);
    if (m >= 1.0 && m <= 64.0) {
        double pr, pi; ipow_c(tr, ti, k, &pr, &pi);
        cx_recip(pr, pi, rr, ri);
    } else {
        double ir, ii; cx_recip(tr, ti, &ir, &ii);
        ipow_c(ir, ii, k, rr, ri);
    }
}

/* ------------------------------------------------------------------ */
/* PolyGamma n >= 1: Hurwitz zeta tail + upward recurrence            */
/* ------------------------------------------------------------------ */

/* Shift threshold for the asymptotic series of psi^(n): Re w >= 10 + n/2. */
static inline double pg_threshold(int n) { return 10.0 + 0.5 * (double)n; }

/* zeta(n+1, w) ~ w^-n/n + w^-(n+1)/2 + sum_k B_2k/(2k)! (n+1)_{2k-1} w^-(n+2k)
 * (DLMF 25.11.43), real w >= pg_threshold(n). False if it fails to converge. */
static bool hz_tail_r(int n, double w, double* out) {
    double r = 1.0 / w, r2 = r * r;
    double rn = ipow_recip_d(w, n);
    double t1 = rn * r;
    double sum = rn / (double)n + 0.5 * t1;
    double rise = (double)n + 1.0;
    double pk = t1 * r;
    for (int k = 1; k <= 24; k++) {
        double term = SFG_B2K_FACT[k - 1] * rise * pk;
        sum += term;
        if (fabs(term) <= 1e-18 * fabs(sum)) { *out = sum; return true; }
        rise *= ((double)n + 2.0 * k) * ((double)n + 2.0 * k + 1.0);
        pk *= r2;
    }
    return false;
}

static bool hz_tail_c(int n, double wr, double wi, double* outr, double* outi) {
    double rr, ri; cx_recip(wr, wi, &rr, &ri);
    double r2r, r2i; cx_mul(rr, ri, rr, ri, &r2r, &r2i);
    double rnr, rni; ipow_recip_c(wr, wi, n, &rnr, &rni);
    double t1r, t1i; cx_mul(rnr, rni, rr, ri, &t1r, &t1i);
    double sr = rnr / (double)n + 0.5 * t1r, si = rni / (double)n + 0.5 * t1i;
    double rise = (double)n + 1.0;
    double pkr, pki; cx_mul(t1r, t1i, rr, ri, &pkr, &pki);
    for (int k = 1; k <= 24; k++) {
        double c = SFG_B2K_FACT[k - 1] * rise;
        double tr = c * pkr, ti = c * pki;
        sr += tr; si += ti;
        if (fabs(tr) + fabs(ti) <= 1e-18 * (fabs(sr) + fabs(si))) {
            *outr = sr; *outi = si; return true;
        }
        rise *= ((double)n + 2.0 * k) * ((double)n + 2.0 * k + 1.0);
        cx_mul(pkr, pki, r2r, r2i, &pkr, &pki);
    }
    return false;
}

bool sfg_polygamma(int n, double x, double* out) {
    if (n == 0) return sfg_digamma(x, out);
    if (n < 0 || n > SFG_POLYGAMMA_MAX_N) return false;
    if (!(x > 0.0) || !isfinite(x)) return false;   /* negative axis: MPFR path */
    double xa = pg_threshold(n);
    int m = x < xa ? (int)ceil(xa - x) : 0;
    double w = x + (double)m;
    double tail;
    if (!hz_tail_r(n, w, &tail)) return false;
    /* w carries the rounding of x + m: zeta(n+1, w + e) = zeta(n+1, w)(1 - n e/w). */
    double ew = two_sum_err(x, (double)m, w);
    if (ew != 0.0) tail *= 1.0 - (double)n * ew / w;
    /* zeta(n+1, x) = sum_{j<m} (x+j)^-(n+1) + zeta(n+1, x+m). Every term is
     * positive; they are added smallest first, compensated, and each carries
     * the first-order correction for the rounding of x + j. */
    double s = tail, c = 0.0;
    for (int j = m - 1; j >= 0; j--) {
        double t = x + (double)j;
        double v = ipow_recip_d(t, n + 1);
        double e = two_sum_err(x, (double)j, t);
        if (e != 0.0) v *= 1.0 - (double)(n + 1) * e / t;
        nsum_add(&s, &c, v);
    }
    double v = sfg_factorial(n) * (s + c);
    if ((n & 1) == 0) v = -v;                        /* (-1)^(n+1) */
    *out = v;
    return isfinite(v) && v != 0.0;
}

/* ------------------------------------------------------------------ */
/* Taylor tiles for lnGamma and psi in the strip near the real axis   */
/* ------------------------------------------------------------------ */

/* In the region |Im z| < 19/4, -5 <= Re z < 10 the shift-to-Stirling route
 * forms lnGamma(z) as the difference of O(10) quantities, losing up to 2^6 in
 * relative accuracy where the answer is O(0.1) (and psi likewise). Instead the
 * exact recurrence moves z into the strip 1 <= Re < 5/2, and a precomputed
 * Taylor series is summed about the nearest of 30 centres (three per row, rows
 * 1/2 apart in Im), so |u| = |z - m - c| <= sqrt(2)/4 while the radius of
 * convergence |c| >= 1.25 (the distance to the pole at 0): the terms fall at
 * least like 0.28^k, and 16-36 of them (fixed per centre, for the tile) put the
 * truncation below 2^-57 of the value. Taylor coefficients are the polygamma
 * values at the centre (DLMF 5.7, 5.15), generated with mpmath at 120 digits
 * by tools/sf_accuracy/gen_gamma_tables.py. */

/* poly4_rc on the real parts of a [k][2] table (the real-axis centres). */
static inline void poly4_rc2(const double (*c)[2], int K, double ur, double ui,
                             double* rr, double* ri) {
    double u2r = ur * ur - ui * ui, u2i = 2.0 * ur * ui;
    double u4r = u2r * u2r - u2i * u2i, u4i = 2.0 * u2r * u2i;
    int j = K - 4;
    double a0r = c[j][0], a1r = c[j + 1][0], a2r = c[j + 2][0], a3r = c[j + 3][0];
    double a0i = 0.0, a1i = 0.0, a2i = 0.0, a3i = 0.0;
    for (j -= 4; j >= 0; j -= 4) {
        CX_STEP(a0r, a0i, c[j][0], 0.0);
        CX_STEP(a1r, a1i, c[j + 1][0], 0.0);
        CX_STEP(a2r, a2i, c[j + 2][0], 0.0);
        CX_STEP(a3r, a3i, c[j + 3][0], 0.0);
    }
    poly4_combine(a0r, a0i, a1r, a1i, a2r, a2i, a3r, a3i, ur, ui, u2r, u2i, rr, ri);
}

/* Evaluate lnGamma (kind 0) or psi (kind 1) at z' = z - m via the tile
 * containing it, for zi >= 0 and -5 <= Re z < 10. m = 0 on the strip
 * 1 <= Re z < 5/2 itself; m < 0 lifts Re z < 1 into [1, 2] (exactly for
 * 0 <= Re z < 1, with one rounding of Re z + |m| below that, where the
 * recurrence factors, not the tile, dominate the value); m > 0 puts Re z' in
 * [3/2, 5/2). Both of lnGamma's
 * real zeros (z = 1, 2) and psi's (x0 = 1.46) therefore lie inside the strip,
 * never across a recurrence step, which would cancel to reach them. For lnGamma
 * off the real axis the low part of the double-double constant term is returned
 * in (*lor, *loi) (zero otherwise). Returns false outside the tiled region.
 * The reductions are exact in double, except the offset from the centre 1.25
 * when it is below 1/8, whose rounding perturbs the argument by at most 2^-56 --
 * harmless, as lnGamma's zeros are factored out and psi's is covered by the
 * root series. */
static bool tile_eval(int kind, double zr, double zi, double* fr, double* fi,
                      double* lor, double* loi, int* m_out) {
    if (!(zr >= -5.0 && zr < 10.0 && zi >= 0.0 && zi < 4.75)) return false;
    int m = zr < 1.0 ? -((int)(1.0 - zr) + 1) : (zr < 2.5 ? 0 : (int)(zr - 0.5) - 1);
    double x1 = zr - (double)(1 + m);           /* Re z' - 1, in [0, 3/2) */
    int j = x1 < 0.5 ? 0 : (x1 < 1.0 ? 1 : 2);  /* centre 1.25, 1.75, 2.25 */
    double ur = x1 - (0.25 + 0.5 * (double)j);
    int bi = (int)(2.0 * zi + 0.5);             /* Im of the centre = bi / 2 */
    double ui = zi - 0.5 * (double)bi;
    int idx = 3 * bi + j;
    if (lor) { *lor = 0.0; *loi = 0.0; }
    if (kind == 0) {
        int K = SFG_TILE_LG_K[idx];
        if (bi == 0) {
            /* lnGamma(z') = (z' - 1)(z' - 2) h, with z' - 1 = x1 + i zi exact */
            double hr, hh; poly4_rc2(SFG_TILE_LG[idx], K, ur, ui, &hr, &hh);
            double qr, qi; cx_mul(x1, zi, x1 - 1.0, zi, &qr, &qi);
            cx_mul(qr, qi, hr, hh, fr, fi);
        } else {
            /* a_0 + u * sum_{k<K} a_{k+1} u^k, with a_0 = lnGamma(c) a double-
             * double: the low part is handed back so Gamma can apply it after
             * the exponential (exp/cos/sin of the rounded sum would otherwise
             * inherit its up-to-half-ulp-of-|lnGamma(c)| error). */
            double pr, pi; poly4_cc(&SFG_TILE_LG[idx][1], K, ur, ui, &pr, &pi);
            double tr, ti; cx_mul(ur, ui, pr, pi, &tr, &ti);
            double a0r = SFG_TILE_LG[idx][0][0], a0i = SFG_TILE_LG[idx][0][1];
            *fr = a0r + tr; *fi = a0i + ti;
            if (lor) {
                *lor = two_sum_err(a0r, tr, *fr) + SFG_TILE_LG_A0LO[idx][0];
                *loi = two_sum_err(a0i, ti, *fi) + SFG_TILE_LG_A0LO[idx][1];
            }
        }
    } else {
        int K = SFG_TILE_PS_K[idx];
        if (bi == 0) poly4_rc2(SFG_TILE_PS[idx], K, ur, ui, fr, fi);
        else         poly4_cc(SFG_TILE_PS[idx], K, ur, ui, fr, fi);
    }
    *m_out = m;
    return true;
}

/* Product P = prod_{j=0}^{N-1} (z + j) together with the number of times the
 * running product crossed the negative real axis, so that
 *   sum_j Log(z + j) = Log(P) + 2 pi i * wraps.
 * For Im z > 0 every factor turns the product counter-clockwise by less than pi,
 * so a crossing is exactly an Im >= 0 -> Im < 0 step; Im z < 0 mirrors it. */
static void shift_product(double zr, double zi, int N, double* pr, double* pi, int* wraps) {
    double qr = 1.0, qi = 0.0;
    int k = 0;
    for (int j = 0; j < N; j++) {
        double nr, ni; cx_mul(qr, qi, zr + (double)j, zi, &nr, &ni);
        if (zi > 0.0) { if (qi >= 0.0 && ni < 0.0) k++; }
        else          { if (qi <= 0.0 && ni > 0.0) k--; }
        qr = nr; qi = ni;
    }
    *pr = qr; *pi = qi; *wraps = k;
}

