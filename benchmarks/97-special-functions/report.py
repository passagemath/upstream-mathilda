#!/usr/bin/env python3
"""report.py -- turn a shootout results JSON into LaTeX table fragments.

Emits, next to special_function_performance.tex (which \\input's them):

  macros.tex          engine versions, platform, date, coverage counts (as \\sf* macros)
  tab_coverage.tex    the 4-engine x 3-regime coverage matrix
  tab_agreement.tex   cross-engine agreement (significant digits) per head x regime
  tab_disagree.tex    the flagged disagreements (the accuracy findings)
  tab_speed_MR.tex    scalar per-call latency, machine real
  tab_speed_C.tex     scalar per-call latency, complex
  tab_speed_AP.tex    scalar per-call latency, arbitrary precision (ap_dps digits)
  tab_throughput.tex  vectorized 10^6-buffer throughput (Mathilda packed vs scipy)
  tab_exact.tex       exact integer/rational arithmetic

Style follows docs/design/performance.md: the fastest cell in a timing row is bold,
a trailing ratio column gives Mathilda vs the fastest other engine, and "--" marks an
absent engine.  No siunitx (the repo uses none); numbers are plain text.
"""
from __future__ import annotations

import datetime as dt
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import registry as R  # noqa: E402

ENGINES = ("mathilda", "wolfram", "maxima", "python")
PRETTY = {"mathilda": "Mathilda", "wolfram": "Mathematica", "maxima": "Maxima", "python": "Python"}
REGIMES = ("MR", "C", "AP")
REGIME_NAME = {"MR": "machine real", "C": "complex", "AP": f"arbitrary precision"}

FAMILY_ORDER = ["Gamma", "Zeta", "Bessel/Airy", "Error", "Elliptic",
                "Orthogonal", "Integral", "Hypergeometric", "Misc"]


def tex_escape(s):
    return str(s).replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


def head_tex(h):
    return r"\mcode{" + h + "}"


def fmt_time(ms, unit):
    if ms is None:
        return None
    v = ms * 1000.0 if unit == "us" else ms
    if v >= 100:
        return f"{v:.0f}"
    if v >= 10:
        return f"{v:.1f}"
    if v >= 1:
        return f"{v:.2f}"
    return f"{v:.3f}"


def fmt_ratio(mth, others):
    o = [t for t in others if t is not None]
    if mth is None or not o:
        return "--"
    best = min(o)
    if best <= 0:
        return "--"
    r = mth / best
    if r < 1:
        return f"\\textbf{{1/{1/r:.1f}}}" if r < 0.95 else "1.0"
    return f"{r:.1f}"


def load_results(path=None):
    if path is None:
        cand = sorted(glob.glob(os.path.join(HERE, "results", "*.json")))
        if not cand:
            sys.exit("no results JSON found; run run_shootout.py first")
        path = cand[-1]
    with open(path) as f:
        return json.load(f), path


def families(cases):
    """Yield (family, [head,...]) in FAMILY_ORDER, heads in registry order."""
    order = [sf.head for sf in R.NUMERIC]
    by_fam = {}
    for h in order:
        if h in cases:
            by_fam.setdefault(cases[h]["family"], []).append(h)
    for fam in FAMILY_ORDER:
        if fam in by_fam:
            yield fam, by_fam[fam]


# ---------------------------------------------------------------- coverage matrix
def gen_coverage(d):
    cases = d["cases"]
    lines = ["% generated by report.py", r"\begingroup\small\setlength{\tabcolsep}{4pt}",
             r"\begin{longtable}{l*{4}{c}}", r"\toprule",
             r"Function & Mathilda & Mathematica & Maxima & Python\\",
             r"& {\footnotesize MR\,C\,AP} & {\footnotesize MR\,C\,AP} & "
             r"{\footnotesize MR\,C\,AP} & {\footnotesize MR\,C\,AP}\\",
             r"\midrule", r"\endfirsthead",
             r"\toprule Function & Mathilda & Mathematica & Maxima & Python\\\midrule \endhead",
             r"\bottomrule \endfoot"]
    counts = {e: {r: 0 for r in REGIMES} for e in ENGINES}
    total = {r: 0 for r in REGIMES}
    for fam, heads in families(cases):
        lines.append(r"\multicolumn{5}{l}{\textit{%s}}\\" % tex_escape(fam))
        for h in heads:
            rj = cases[h]["regimes"]
            cells = []
            for e in ENGINES:
                marks = []
                for reg in REGIMES:
                    if reg in rj:
                        cov = rj[reg]["coverage"].get(e, False)
                        marks.append(r"\yes" if cov else r"\no")
                        if cov:
                            counts[e][reg] += 1
                    else:
                        marks.append(r"\na")
                cells.append(r"\,".join(marks))
            for reg in REGIMES:
                if reg in rj:
                    total[reg] += 1
            lines.append(f"{head_tex(h)} & " + " & ".join(cells) + r"\\")
    lines += [r"\bottomrule", r"\end{longtable}", r"\endgroup"]
    return "\n".join(lines) + "\n", counts, total


# ---------------------------------------------------------------- agreement
def gen_agreement(d):
    cases = d["cases"]
    lines = ["% generated by report.py", r"\begingroup\small",
             r"\begin{longtable}{lccc}", r"\toprule",
             r"Function & MR & Complex & Arb.\ prec.\\",
             r"& \footnotesize(digits) & \footnotesize(digits) & \footnotesize(digits)\\",
             r"\midrule", r"\endfirsthead",
             r"\toprule Function & MR & Complex & Arb.\ prec.\\\midrule \endhead",
             r"\bottomrule \endfoot"]
    for fam, heads in families(cases):
        lines.append(r"\multicolumn{4}{l}{\textit{%s}}\\" % tex_escape(fam))
        for h in heads:
            rj = cases[h]["regimes"]
            cells = []
            for reg in REGIMES:
                if reg not in rj:
                    cells.append("--")
                    continue
                a = rj[reg]["agree_digits"]
                cells.append("--" if a is None else f"{a:.1f}")
            lines.append(f"{head_tex(h)} & " + " & ".join(cells) + r"\\")
    lines += [r"\bottomrule", r"\end{longtable}", r"\endgroup"]
    return "\n".join(lines) + "\n"


def gen_disagree(d):
    cases = d["cases"]
    rows = []
    for h, cj in cases.items():
        for reg, rj in cj["regimes"].items():
            for dd in rj.get("disagree", []):
                rows.append((h, reg, dd["engine"], dd["digits"]))
    rows.sort(key=lambda r: r[3])
    lines = ["% generated by report.py", r"\begin{longtable}{llcr}", r"\toprule",
             r"Function & Regime & Engine & Agreement (digits)\\\midrule", r"\endhead"]
    if not rows:
        lines.append(r"\multicolumn{4}{l}{\textit{None: every engine agreed with the consensus "
                     r"to within tolerance in every regime.}}\\")
    for h, reg, e, dg in rows:
        lines.append(f"{head_tex(h)} & {REGIME_NAME[reg]} & {PRETTY[e]} & {dg:.1f}\\\\")
    lines += [r"\bottomrule", r"\end{longtable}"]
    return "\n".join(lines) + "\n", rows


# ---------------------------------------------------------------- scalar speed
def gen_speed(d, regime):
    cases = d["cases"]
    unit = "ms" if regime == "AP" else "us"
    ulabel = "ms" if regime == "AP" else r"$\mu$s"
    lines = ["% generated by report.py", r"\begingroup\small\setlength{\tabcolsep}{5pt}",
             r"\begin{longtable}{lrrrrr}", r"\toprule",
             r"Function & Mathilda & Mathematica & Maxima & Python & M/best\\",
             r"\multicolumn{5}{l}{\footnotesize net per-call latency (%s), loop floor subtracted} &\\" % ulabel,
             r"\midrule", r"\endfirsthead",
             r"\toprule Function & Mathilda & Mathematica & Maxima & Python & M/best\\\midrule \endhead",
             r"\bottomrule \endfoot"]
    ratios = []
    for fam, heads in families(cases):
        heads = [h for h in heads if regime in cases[h]["regimes"]]
        if not heads:
            continue
        lines.append(r"\multicolumn{6}{l}{\textit{%s}}\\" % tex_escape(fam))
        for h in heads:
            t = cases[h]["regimes"][regime]["time_ms"]
            sus = set(cases[h]["regimes"][regime].get("cache_suspect", []))
            # A cache-suspect cell (its canary repeat ran far faster than the first pass)
            # measured a memo, not a kernel: shown with a dagger, never ranked.
            vals = {e: (None if e in sus else t.get(e)) for e in ENGINES}
            present = [v for v in vals.values() if v is not None]
            best = min(present) if present else None
            cells = []
            for e in ENGINES:
                s = fmt_time(vals[e], unit)
                if e in sus:
                    cells.append(r"%s$^\dagger$" % fmt_time(t.get(e), unit))
                elif s is None:
                    cells.append("--")
                elif vals[e] == best:
                    cells.append(r"\textbf{%s}" % s)
                else:
                    cells.append(s)
            others = [vals[e] for e in ENGINES if e != "mathilda"]
            ratio = fmt_ratio(vals["mathilda"], others)
            if vals["mathilda"] is not None and any(o is not None for o in others):
                o = [x for x in others if x is not None]
                ratios.append(vals["mathilda"] / min(o))
            lines.append(f"{head_tex(h)} & " + " & ".join(cells) + f" & {ratio}" + r"\\")
    lines += [r"\bottomrule", r"\end{longtable}", r"\endgroup"]
    return "\n".join(lines) + "\n", ratios


# ---------------------------------------------------------------- throughput
def gen_throughput(d):
    """Array-native throughput: Mathilda's packed buffer vs SciPy's NumPy array.

    Mathematica and Maxima have no comparable array-native special-function call under
    ``wolframscript -file`` (they scalar-thread, tens of seconds for 10^6 elements), so
    they are omitted here -- this table is the honest array-vs-array comparison.
    """
    thru = d.get("throughput")
    if not thru:
        return None
    order = [sf.head for sf in R.NUMERIC]
    heads = sorted(set(thru.get("mathilda", {})) | set(thru.get("python", {})),
                   key=lambda h: order.index(h) if h in order else 999)
    lines = ["% generated by report.py", r"\begingroup\small",
             r"\begin{longtable}{lrrr}", r"\toprule",
             r"Function & Mathilda & Python/SciPy & M/SciPy\\",
             r"\multicolumn{3}{l}{\footnotesize $10^6$-element buffer, ms} &\\\midrule", r"\endhead",
             r"\bottomrule \endfoot"]
    for h in heads:
        m = thru.get("mathilda", {}).get(h)
        p = thru.get("python", {}).get(h)
        if m is None and p is None:
            continue
        best = min([v for v in (m, p) if v is not None])
        cs = []
        for v in (m, p):
            s = fmt_time(v, "ms")
            cs.append("--" if s is None else (r"\textbf{%s}" % s if v == best else s))
        ratio = fmt_ratio(m, [p])
        lines.append(f"{head_tex(h)} & " + " & ".join(cs) + f" & {ratio}" + r"\\")
    lines += [r"\bottomrule", r"\end{longtable}", r"\endgroup"]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- exact
def gen_exact(d):
    ex = d.get("exact")
    if not ex:
        return None
    sizes = ex["sizes"]
    eng = ex["engines"]
    lines = ["% generated by report.py", r"\begingroup\small\setlength{\tabcolsep}{5pt}",
             r"\begin{longtable}{llrrrr}", r"\toprule",
             r"Function & $n$ & Mathilda & Mathematica & Maxima & Python\\",
             r"\multicolumn{6}{l}{\footnotesize time (ms); value agreement checked at the smallest $n$} \\\midrule",
             r"\endhead", r"\bottomrule \endfoot"]
    for h, szs in sizes.items():
        for n in szs:
            key = f"{h}:{n}"
            cells = []
            for e in ENGINES:
                tm = eng.get(e, {}).get("t", {}).get(key)
                s = fmt_time(tm, "ms")
                cells.append("--" if s is None else s)
            label = head_tex(h) if n == szs[0] else ""
            lines.append(f"{label} & {n} & " + " & ".join(cells) + r"\\")
    lines += [r"\bottomrule", r"\end{longtable}", r"\endgroup"]
    # value agreement at smallest n
    agree_lines = []
    for h, szs in sizes.items():
        n0 = szs[0]
        key = f"{h}:{n0}"
        vals = {e: eng.get(e, {}).get("v", {}).get(key) for e in ENGINES}
        present = {e: v for e, v in vals.items() if v}
        ok = len(set(present.values())) == 1 and len(present) >= 2
        agree_lines.append((h, n0, len(present), ok))
    return "\n".join(lines) + "\n", agree_lines


# ---------------------------------------------------------------- macros
def gen_macros(d, cov_counts, cov_total, disagree_rows, speed_ratios, exact_agree):
    m = d["meta"]
    e = m["engines"]

    def med(xs):
        xs = sorted(xs)
        return xs[len(xs) // 2] if xs else 0

    lines = ["% generated by report.py", r"\makeatletter"]

    def defm(name, val):
        lines.append(f"\\newcommand{{\\{name}}}{{{val}}}")

    defm("sfdate", m["date"])
    defm("sfplatform", tex_escape(m["platform"]))
    defm("sfapdps", m["ap_dps"])
    defm("sfmathilda", tex_escape(e.get("mathilda", "")))
    defm("sfwolfram", tex_escape(e.get("wolfram", "")))
    defm("sfmaxima", tex_escape(e.get("maxima", "")))
    defm("sfpython", tex_escape(e.get("python", "")))
    defm("sfncases", len(d["cases"]))
    for eng in ENGINES:
        for reg in REGIMES:
            defm(f"sfcov{eng}{reg}", cov_counts[eng][reg])
    for reg in REGIMES:
        defm(f"sftotal{reg}", cov_total[reg])
    defm("sfndisagree", len(disagree_rows))
    for reg, rs in speed_ratios.items():
        mr = med([r for r in rs])
        # express as "N.N faster" / "N.N slower"
        if mr < 1:
            defm(f"sfspeed{reg}", f"{1/mr:.1f}$\\times$ faster")
        else:
            defm(f"sfspeed{reg}", f"{mr:.1f}$\\times$ slower")
    nexact_ok = sum(1 for (_, _, _, ok) in exact_agree if ok) if exact_agree else 0
    defm("sfexactok", nexact_ok)
    lines.append(r"\makeatother")
    return "\n".join(lines) + "\n"


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else None
    d, used = load_results(path)
    print(f"[report] using {used}")

    cov, cov_counts, cov_total = gen_coverage(d)
    open(os.path.join(HERE, "tab_coverage.tex"), "w").write(cov)

    open(os.path.join(HERE, "tab_agreement.tex"), "w").write(gen_agreement(d))
    dis, dis_rows = gen_disagree(d)
    open(os.path.join(HERE, "tab_disagree.tex"), "w").write(dis)

    speed_ratios = {}
    for reg in REGIMES:
        frag, ratios = gen_speed(d, reg)
        open(os.path.join(HERE, f"tab_speed_{reg}.tex"), "w").write(frag)
        speed_ratios[reg] = ratios

    thru = gen_throughput(d)
    if thru:
        open(os.path.join(HERE, "tab_throughput.tex"), "w").write(thru)

    exact_agree = None
    ex = gen_exact(d)
    if ex:
        frag, exact_agree = ex
        open(os.path.join(HERE, "tab_exact.tex"), "w").write(frag)

    macros = gen_macros(d, cov_counts, cov_total, dis_rows, speed_ratios, exact_agree or [])
    open(os.path.join(HERE, "macros.tex"), "w").write(macros)

    print(f"[report] coverage counts: " +
          ", ".join(f"{PRETTY[e]}={sum(cov_counts[e].values())}" for e in ENGINES))
    print(f"[report] disagreements: {len(dis_rows)}")
    for reg in REGIMES:
        rs = speed_ratios[reg]
        if rs:
            srt = sorted(rs)
            print(f"[report] {reg} median Mathilda/best ratio = {srt[len(srt)//2]:.2f}  (n={len(rs)})")
    print("[report] wrote tab_*.tex + macros.tex")


if __name__ == "__main__":
    main()
