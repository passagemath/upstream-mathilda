#!/usr/bin/env python3
"""Generate the named-character tables used by the lexer.

Usage:
  tools/gen_named_chars.py <UnicodeCharacters.tr> > src/strings/named_chars.inc
  tools/gen_named_chars.py --classes <classes.tsv> > src/strings/named_char_class.inc

named_chars.inc is the \\[Name] -> code point table used by the string-literal
lexer and by \\[Name] escapes in source (utf8.c: u8_named_char).  The input is
FrontEnd/TextResources/UnicodeCharacters.tr; each data line is
`0xHHHH <tab><tab> \\[Name] ...`.  Entries are sorted by name in strcmp (byte)
order, as u8_named_char's binary search requires.

named_char_class.inc says how the PARSER treats each non-ASCII code point in
source code (utf8.c: u8_char_class).  Its input is the TSV written by
tools/classify_named_chars.wls, which asks the reference parser about every
name.  A code point absent from the table is a letter (it forms identifiers),
so only the exceptions are listed: operators, whitespace, line breaks, the
letters that alone alias a System symbol (\\[Pi] is Pi), and characters that
cannot appear in source at all.  Sorted by code point for binary search.

Reference precedences (Precedence[head], 10..1000) are mapped onto the parser's
1..10000 ladder by piecewise-linear interpolation between the operators both
share (`;` 10 -> 100, `=` 40 -> 500, `+` 310 -> 3500, `^` 590 -> 6500, ...),
which preserves their relative order -- all the parser needs."""
import re, sys

# (reference precedence, parser precedence) for operators with ASCII spellings.
ANCHORS = [(10, 100), (40, 500), (70, 800), (90, 1000), (110, 1200), (120, 1500),
           (130, 1700), (150, 2200), (160, 2300), (170, 2500), (215, 2750),
           (230, 3000), (290, 3200), (310, 3500), (400, 4500), (470, 5000),
           (490, 5300), (510, 5900), (590, 6500), (600, 6700), (620, 7000),
           (670, 7700), (1000, 9500)]

def ladder(p):
    if p <= ANCHORS[0][0]:
        return ANCHORS[0][1]
    for (a, x), (b, y) in zip(ANCHORS, ANCHORS[1:]):
        if a <= p <= b:
            return round(x + (y - x) * (p - a) / (b - a))
    return ANCHORS[-1][1]

def gen_names(path):
    entries = {}
    for line in open(path, encoding="utf-8", errors="replace"):
        m = re.match(r"0x([0-9A-Fa-f]+)\s+\\\[([A-Za-z0-9]+)\]", line)
        if m:
            entries.setdefault(m.group(2), int(m.group(1), 16))
    print("/* Generated by tools/gen_named_chars.py -- do not edit. */")
    for name in sorted(entries, key=lambda s: s.encode()):
        print(f'    {{"{name}", 0x{entries[name]:04X}u}},')

CLS = {"LETTER": "U8C_LETTER", "SPACE": "U8C_SPACE", "NEWLINE": "U8C_NEWLINE",
       "INFIX": "U8C_INFIX", "PREFIX": "U8C_PREFIX", "POSTFIX": "U8C_POSTFIX",
       "OTHER": "U8C_OTHER"}
ASSOC = {"FLAT": "U8A_FLAT", "LEFT": "U8A_LEFT", "RIGHT": "U8A_RIGHT", "": "U8A_NONE",
         "OTHER": "U8A_NONE"}

def gen_classes(path):
    by_cp = {}
    for line in open(path, encoding="utf-8"):
        f = line.rstrip("\n").split("\t")
        if len(f) < 6:
            continue
        name, cp, cls, head, assoc, prec = f[:6]
        cp = int(cp, 16)
        if cp < 0x80:
            continue                      # \[RawPlus] etc.: the ASCII character itself
        if cls == "LETTER" and not head:
            continue                      # the default
        if cls == "CONSTANT":             # never produced for a non-blank alone
            continue
        if not re.fullmatch(r"[A-Za-z$][A-Za-z0-9$]*", head or "x"):
            cls, head = "OTHER", ""       # e.g. Derivative[1]: not a plain head
        pr = ladder(float(prec)) if prec else 0
        old = by_cp.get(cp)
        if old is None or old[0] == "OTHER":
            by_cp[cp] = (cls, head, assoc, pr, name)
    print("/* Generated by tools/gen_named_chars.py --classes -- do not edit. */")
    for cp in sorted(by_cp):
        cls, head, assoc, pr, name = by_cp[cp]
        h = f'"{head}"' if head else "NULL"
        print(f"    {{0x{cp:04X}u, {CLS[cls]}, {ASSOC.get(assoc, 'U8A_NONE')}, {pr}, {h}}},"
              f"  /* {name} */")

if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--classes":
        gen_classes(sys.argv[2])
    elif len(sys.argv) == 2:
        gen_names(sys.argv[1])
    else:
        sys.exit(__doc__)
