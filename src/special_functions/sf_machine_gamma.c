static inline void cx_mul(double ar, double ai, double br, double bi,
                          double* rr, double* ri) {
    double re = ar * br - ai * bi;
    double im = ar * bi + ai * br;
    *rr = re; *ri = im;
}

/* 1 / (a + i b). One division in the common range; Smith's scaled form
 * (Smith 1962, CACM 5) when |a|, |b| could over/underflow when squared. */
static inline void cx_recip(double ar, double ai, double* rr, double* ri) {
    double m = fabs(ar) > fabs(ai) ? fabs(ar) : fabs(ai);
    if (m > 1e-150 && m < 1e150) {
        double d = 1.0 / (ar * ar + ai * ai);
        *rr = ar * d; *ri = -ai * d;
    } else if (fabs(ar) >= fabs(ai)) {
        double q = ai / ar, d = ar + ai * q;
        *rr = 1.0 / d; *ri = -q / d;
    } else {
        double q = ar / ai, d = ai + ar * q;
        *rr = q / d; *ri = -1.0 / d;
    }
}

/* log|z| without overflow / underflow in the squares. */
static inline double cx_logabs(double ar, double ai) {
    double m = fabs(ar) > fabs(ai) ? fabs(ar) : fabs(ai);
    if (m > 1e-150 && m < 1e150) return 0.5 * log(ar * ar + ai * ai);
    return log(hypot(ar, ai));
}

/* Principal log. */
static inline void cx_log(double ar, double ai, double* rr, double* ri) {
    *rr = cx_logabs(ar, ai);
    *ri = atan2(ai, ar);
}

/* log(1 + u), accurate for small |u| (the real part through log1p). */
static inline void cx_log1p(double ur, double ui, double* rr, double* ri) {
    *rr = 0.5 * log1p(ur * (2.0 + ur) + ui * ui);
    *ri = atan2(ui, 1.0 + ur);
}

/* exp(z). */
static inline void cx_exp(double ar, double ai, double* rr, double* ri) {
    double m = exp(ar);
    *rr = m * cos(ai);
    *ri = m * sin(ai);
}

/* r^k for a non-negative integer k, by binary powering. */
static inline double ipow_d(double r, int k) {
    double res = 1.0;
    while (k) { if (k & 1) res *= r; r *= r; k >>= 1; }
    return res;
}
static inline void ipow_c(double ar, double ai, int k, double* rr, double* ri) {
    double pr = 1.0, pi = 0.0;
    while (k) {
        if (k & 1) cx_mul(pr, pi, ar, ai, &pr, &pi);
        k >>= 1;
        if (k) cx_mul(ar, ai, ar, ai, &ar, &ai);
    }
    *rr = pr; *ri = pi;
}

/* Polynomials sum_{k<K} c[k] u^k, K a multiple of 4, by Estrin's split into
 * four interleaved Horner chains in u^4:
 *     P(u) = Q0(u^4) + u Q1(u^4) + u^2 (Q2(u^4) + u Q3(u^4)).
 * The four chains are independent, so the dependent-latency chain is a quarter
 * of plain Horner's -- the series here run to 24-40 terms, and on a core
 * without FMA a Horner step is a ~12-cycle dependency. */
static inline double poly4_rr(const double* c, int K, double u) {
    double u2 = u * u, u4 = u2 * u2;
    int j = K - 4;
    double a0 = c[j], a1 = c[j + 1], a2 = c[j + 2], a3 = c[j + 3];
    for (j -= 4; j >= 0; j -= 4) {
        a0 = a0 * u4 + c[j];
        a1 = a1 * u4 + c[j + 1];
        a2 = a2 * u4 + c[j + 2];
        a3 = a3 * u4 + c[j + 3];
    }
    return (a0 + u * a1) + u2 * (a2 + u * a3);
}

#define CX_STEP(ar, ai, cr, ci)  do { double t_ = ar * u4r - ai * u4i + (cr); \
        ai = ar * u4i + ai * u4r + (ci); ar = t_; } while (0)

static inline void poly4_combine(double a0r, double a0i, double a1r, double a1i,
                                 double a2r, double a2i, double a3r, double a3i,
                                 double ur, double ui, double u2r, double u2i,
                                 double* rr, double* ri) {
    double hr, hi; cx_mul(ur, ui, a3r, a3i, &hr, &hi);      /* Q2 + u Q3 */
    hr += a2r; hi += a2i;
    cx_mul(u2r, u2i, hr, hi, &hr, &hi);
    double lr, li; cx_mul(ur, ui, a1r, a1i, &lr, &li);      /* Q0 + u Q1 */
    *rr = lr + a0r + hr;
    *ri = li + a0i + hi;
}

/* Real coefficients, complex u. */
static inline void poly4_rc(const double* c, int K, double ur, double ui,
                            double* rr, double* ri) {
    double u2r = ur * ur - ui * ui, u2i = 2.0 * ur * ui;
    double u4r = u2r * u2r - u2i * u2i, u4i = 2.0 * u2r * u2i;
    int j = K - 4;
    double a0r = c[j], a1r = c[j + 1], a2r = c[j + 2], a3r = c[j + 3];
    double a0i = 0.0, a1i = 0.0, a2i = 0.0, a3i = 0.0;
    for (j -= 4; j >= 0; j -= 4) {
        CX_STEP(a0r, a0i, c[j], 0.0);
        CX_STEP(a1r, a1i, c[j + 1], 0.0);
        CX_STEP(a2r, a2i, c[j + 2], 0.0);
        CX_STEP(a3r, a3i, c[j + 3], 0.0);
    }
    poly4_combine(a0r, a0i, a1r, a1i, a2r, a2i, a3r, a3i, ur, ui, u2r, u2i, rr, ri);
}

/* Complex coefficients c[k][2], complex u. */
static inline void poly4_cc(const double (*c)[2], int K, double ur, double ui,
                            double* rr, double* ri) {
    double u2r = ur * ur - ui * ui, u2i = 2.0 * ur * ui;
    double u4r = u2r * u2r - u2i * u2i, u4i = 2.0 * u2r * u2i;
    int j = K - 4;
    double a0r = c[j][0], a1r = c[j + 1][0], a2r = c[j + 2][0], a3r = c[j + 3][0];
    double a0i = c[j][1], a1i = c[j + 1][1], a2i = c[j + 2][1], a3i = c[j + 3][1];
    for (j -= 4; j >= 0; j -= 4) {
        CX_STEP(a0r, a0i, c[j][0], c[j][1]);
        CX_STEP(a1r, a1i, c[j + 1][0], c[j + 1][1]);
        CX_STEP(a2r, a2i, c[j + 2][0], c[j + 2][1]);
        CX_STEP(a3r, a3i, c[j + 3][0], c[j + 3][1]);
    }
    poly4_combine(a0r, a0i, a1r, a1i, a2r, a2i, a3r, a3i, ur, ui, u2r, u2i, rr, ri);
}

static inline double sfg_factorial(int n) {
    return n <= 22 ? SFG_FACT[n] : tgamma((double)n + 1.0);
}

